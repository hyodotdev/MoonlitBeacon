// Binary-only internal update: ship a new AAB while reusing the already
// committed store gallery byte for byte. The full apply path always deletes
// and reuploads all 100 listing images; this path never calls the listing,
// image, product, promotion, or review endpoints, so it cannot drift the
// approved gallery. Reuse here is an explicit operator decision recorded in
// the mode and the receipt below; it is not fresh capture evidence and it is
// not the pending native purchase evidence.
