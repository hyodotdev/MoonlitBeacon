function sha256(contents) {
  return createHash('sha256').update(contents).digest('hex');
}

function canonicalJson(value) {
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(',')}]`;
  if (value !== null && typeof value === 'object') {
    return `{${Object.keys(value).sort().map((key) => (
      `${JSON.stringify(key)}:${canonicalJson(value[key])}`
    )).join(',')}}`;
  }
  return JSON.stringify(value);
}

function deepFreeze(value) {
  if (value && typeof value === 'object' && !Object.isFrozen(value)) {
    Object.freeze(value);
    for (const child of Object.values(value)) deepFreeze(child);
  }
  return value;
}

function isInside(parent, child) {
  const relation = relative(resolve(parent), resolve(child));
  return relation === ''
    || (
      relation !== '..'
      && !relation.startsWith(`..${sep}`)
      && !isAbsolute(relation)
    );
}

function assertRelativePath(value, label) {
  if (
    typeof value !== 'string'
    || value === ''
    || value.includes('\0')
    || isAbsolute(value)
    || value.split(/[\\/]/u).some((part) => part === '' || part === '..')
  ) {
    throw new Error(`${label} must be a safe repository-relative path.`);
  }
  return value;
}

function normalizeRelative(value) {
  return value.replaceAll('\\', '/');
}

function assertRoot(root) {
  if (typeof root !== 'string' || !isAbsolute(root) || !existsSync(root)) {
    throw new Error('Repository root must be an existing absolute path.');
  }
  return realpathSync(root);
}

function assertNoSymlinkChain(rootReal, absolutePath, label) {
  const relation = relative(rootReal, absolutePath);
  let current = rootReal;
  for (const part of relation.split(sep).filter(Boolean)) {
    current = resolve(current, part);
    if (lstatSync(current).isSymbolicLink()) {
      throw new Error(`${label} contains a symbolic link.`);
    }
  }
}

function resolveRepoInput(root, relativePath, label, { directory = false } = {}) {
  const rootReal = assertRoot(root);
  assertRelativePath(relativePath, label);
  const absolutePath = resolve(rootReal, relativePath);
  if (!isInside(rootReal, absolutePath) || !existsSync(absolutePath)) {
    throw new Error(`${label} is missing or points outside the repository: ${relativePath}`);
  }
  assertNoSymlinkChain(rootReal, absolutePath, label);
  const info = lstatSync(absolutePath);
  if (directory ? !info.isDirectory() : !info.isFile()) {
    throw new Error(`${label} is not a ${directory ? 'directory' : 'regular file'}.`);
  }
  return absolutePath;
}

export function resolveRepoOutput(root, relativePath, label) {
  const rootReal = assertRoot(root);
  assertRelativePath(relativePath, label);
  const absolutePath = resolve(rootReal, relativePath);
  if (!isInside(rootReal, absolutePath)) {
    throw new Error(`${label} points outside the repository.`);
  }
  const parent = dirname(absolutePath);
  if (!existsSync(parent) || !lstatSync(parent).isDirectory()) {
    throw new Error(`${label} parent directory is missing.`);
  }
  assertNoSymlinkChain(rootReal, parent, `${label} parent path`);
  if (existsSync(absolutePath) && lstatSync(absolutePath).isSymbolicLink()) {
    throw new Error(`${label} is a symbolic link.`);
  }
  return absolutePath;
}

function walkRegularFiles(rootReal, relativePath, label) {
  assertRelativePath(relativePath, label);
  const absolutePath = resolve(rootReal, relativePath);
  if (!isInside(rootReal, absolutePath) || !existsSync(absolutePath)) {
    throw new Error(`${label} is missing or points outside the repository.`);
  }
  assertNoSymlinkChain(rootReal, absolutePath, label);
  const info = lstatSync(absolutePath);
  if (info.isSymbolicLink()) {
    throw new Error(`${label} contains a symbolic link.`);
  }
  if (info.isFile()) return [absolutePath];
  if (!info.isDirectory()) {
    throw new Error(`${label} must be a regular file or directory.`);
  }
  const files = [];
  for (const name of readdirSync(absolutePath).sort((left, right) =>
    left.localeCompare(right, 'en'))) {
    files.push(...walkRegularFiles(
      rootReal,
      normalizeRelative(relative(rootReal, resolve(absolutePath, name))),
      label,
    ));
  }
  return files;
}

function assertBundleIsFresh(rootReal, bundleAbsolute, dependencies) {
  const files = dependencies.flatMap((relativePath) =>
    walkRegularFiles(rootReal, relativePath, 'binary-only bundle freshness dependency'));
  if (files.length === 0) {
    throw new Error('binary-only bundle freshness dependency is empty.');
  }
  const newest = files.reduce((best, filePath) => {
    const mtimeMs = lstatSync(filePath).mtimeMs;
    return mtimeMs > best.mtimeMs ? { filePath, mtimeMs } : best;
  }, { filePath: '', mtimeMs: Number.NEGATIVE_INFINITY });
  const bundleMtimeMs = lstatSync(bundleAbsolute).mtimeMs;
  if (bundleMtimeMs + 1 < newest.mtimeMs) {
    throw new Error(
      'binary-only AAB input is stale. '
      + `newer than ${relative(rootReal, bundleAbsolute)}: `
      + `${relative(rootReal, newest.filePath)} is newer.`,
    );
  }
  return true;
}

function readStableBytes(path, label) {
  let descriptor;
  try {
    descriptor = openSync(path, fsConstants.O_RDONLY | (fsConstants.O_NOFOLLOW ?? 0));
    const before = fstatSync(descriptor);
    if (!before.isFile()) throw new Error(`${label} is not a regular file.`);
    const contents = readFileSync(descriptor);
    const after = fstatSync(descriptor);
    if (
      before.dev !== after.dev
      || before.ino !== after.ino
      || before.size !== after.size
      || before.mtimeMs !== after.mtimeMs
    ) {
      throw new Error(`${label} changed while being read.`);
    }
    return contents;
  } finally {
    if (descriptor !== undefined) closeSync(descriptor);
  }
}

function manifestFileRecord(manifest, relativePath, label) {
  if (!Array.isArray(manifest?.files)) {
    throw new Error('binary-only manifest file record is missing.');
  }
  const matches = manifest.files.filter((file) => file?.path === relativePath);
  if (matches.length !== 1) {
    throw new Error(`${label} manifest file record is missing or duplicated.`);
  }
  const record = matches[0];
  if (
    !Number.isSafeInteger(record.bytes)
    || record.bytes < 1
    || typeof record.sha256 !== 'string'
    || !/^[0-9a-f]{64}$/u.test(record.sha256)
  ) {
    throw new Error(`${label} manifest file record is invalid.`);
  }
  return record;
}

function readRetainedJson(outputPath, manifest, relativePath, label) {
  const record = manifestFileRecord(manifest, relativePath, label);
  assertRelativePath(relativePath, label);
  const outputReal = realpathSync(outputPath);
  const absolutePath = resolve(outputReal, relativePath);
  if (!isInside(outputReal, absolutePath) || !existsSync(absolutePath)) {
    throw new Error(`${label} is not in the retained package.`);
  }
  let current = outputReal;
  for (const part of relativePath.split('/')) {
    current = resolve(current, part);
    if (lstatSync(current).isSymbolicLink()) {
      throw new Error(`${label} contains a symbolic link.`);
    }
  }
  const contents = readStableBytes(absolutePath, label);
  if (contents.length !== record.bytes || sha256(contents) !== record.sha256) {
    throw new Error(`${label} differs from the retained manifest snapshot.`);
  }
  try {
    return JSON.parse(contents.toString('utf8'));
  } catch {
    throw new Error(`${label} JSON is invalid.`);
  }
}

function expectedImageCount(imageType) {
  if (imageType === 'icon' || imageType === 'featureGraphic') return 1;
  const target = PLAY_SCREENSHOT_TARGETS.find(
    (candidate) => candidate.imageType === imageType,
  );
  if (!target) throw new Error(`binary-only image type is outside the contract: ${imageType}`);
  return PLAY_SCREENSHOT_NAMES.length;
}

function collectRetainedGallery(outputPath, manifest) {
  const listings = PLAY_LOCALES.map((locale) => {
    const operation = readRetainedJson(
      outputPath,
      manifest,
      `publisher-api/edits.listings.update/${locale}.json`,
      `${locale} retained listing`,
    );
    if (
      operation.apiBoundary !== 'edits.listings.update'
      || operation.method !== 'PUT'
      || operation.body?.language !== locale
      || typeof operation.body?.title !== 'string'
      || typeof operation.body?.shortDescription !== 'string'
      || typeof operation.body?.fullDescription !== 'string'
    ) {
      throw new Error(`${locale} retained listing contract differs.`);
    }
    return {
      body: {
        fullDescription: operation.body.fullDescription,
        language: locale,
        shortDescription: operation.body.shortDescription,
        title: operation.body.title,
      },
      language: locale,
    };
  });
  const notes = readRetainedJson(
    outputPath,
    manifest,
    'publisher-api/edits.tracks.update/release-notes.json',
    'binary-only retained release notes',
  );
  const releaseNotes = notes.futureTrackReleaseFragment?.releaseNotes;
  if (
    notes.apiBoundary !== 'edits.tracks.update'
    || !Array.isArray(releaseNotes)
    || releaseNotes.length !== PLAY_LOCALES.length
    || releaseNotes.some((note, index) => (
      note?.language !== PLAY_LOCALES[index]
      || typeof note?.text !== 'string'
      || note.text === ''
      || [...note.text].length > PLAY_RELEASE_NOTE_MAX_CHARACTERS
    ))
  ) {
    throw new Error('binary-only retained release-note contract differs.');
  }
  const images = readRetainedJson(
    outputPath,
    manifest,
    'publisher-api/edits.images.upload/operations.json',
    'binary-only retained image plan',
  );
  const expectedUploads = PLAY_LOCALES.length
    * (2 + PLAY_SCREENSHOT_TARGETS.length * PLAY_SCREENSHOT_NAMES.length);
  if (
    images.apiBoundary !== 'edits.images.upload'
    || !Array.isArray(images.uploadOperations)
    || images.uploadOperations.length !== expectedUploads
  ) {
    throw new Error('binary-only retained image count differs from the 100-image contract.');
  }
  const uploads = images.uploadOperations.map((operation, index) => {
    if (
      operation.method !== 'POST'
      || !PLAY_LOCALES.includes(operation.language)
      || !PLAY_BINARY_ONLY_IMAGE_TYPES.includes(operation.imageType)
      || typeof operation.sha256 !== 'string'
      || !/^[0-9a-f]{64}$/u.test(operation.sha256)
      || typeof operation.mediaPath !== 'string'
    ) {
      throw new Error(`binary-only retained image operation ${index + 1} contract differs.`);
    }
    const mediaRecord = manifestFileRecord(
      manifest,
      operation.mediaPath,
      `retained image ${operation.language}/${operation.imageType}`,
    );
    if (mediaRecord.sha256 !== operation.sha256) {
      throw new Error('binary-only retained image operation and manifest file hash differ.');
    }
    return {
      imageType: operation.imageType,
      language: operation.language,
      mediaPath: operation.mediaPath,
      sequence: operation.sequence ?? null,
      sha256: operation.sha256,
    };
  });
  for (const locale of PLAY_LOCALES) {
    for (const imageType of PLAY_BINARY_ONLY_IMAGE_TYPES) {
      const count = uploads.filter((operation) => (
        operation.language === locale && operation.imageType === imageType
      )).length;
      if (count !== expectedImageCount(imageType)) {
        throw new Error(
          `binary-only retained ${locale}/${imageType} image count differs.`,
        );
      }
    }
  }
  const galleryDigest = sha256(canonicalJson({
    images: uploads.map(({ imageType, language, sequence, sha256: digest }) => ({
      imageType,
      language,
      sequence,
      sha256: digest,
    })),
    listings: listings.map(({ body, language }) => ({ body, language })),
  }));
  return { galleryDigest, listings, releaseNotes, uploads };
}

function readProjectPresetIdentity(rootReal) {
  const projectPath = resolve(
    rootReal,
    normalizeRelative(DEFAULT_PLAY_RELEASE_INPUTS.projectGodot),
  );
  const presetsPath = resolve(
    rootReal,
    normalizeRelative(DEFAULT_PLAY_RELEASE_INPUTS.exportPresets),
  );
  for (const [path, label] of [
    [projectPath, 'Godot project settings'],
    [presetsPath, 'Godot export preset'],
  ]) {
    if (!isInside(rootReal, path) || !existsSync(path)) {
      throw new Error(`${label} is missing or points outside the repository.`);
    }
    assertNoSymlinkChain(rootReal, path, label);
    if (!lstatSync(path).isFile()) {
      throw new Error(`${label} is not a regular file.`);
    }
  }
  const metadata = readAndroidReleaseMetadata(
    readFileSync(projectPath, 'utf8'),
    readFileSync(presetsPath, 'utf8'),
  );
  assertAndroidReleaseMetadata(metadata, {
    expectedPackageName: PLAY_PACKAGE_NAME,
  });
  return metadata;
}

function partitionManifestInputs(manifest, bundleRelative) {
  if (!Array.isArray(manifest?.inputs) || manifest.inputs.length === 0) {
    throw new Error('binary-only retained manifest input record is missing.');
  }
  const excluded = new Set([
    normalizeRelative(bundleRelative),
    normalizeRelative(DEFAULT_PLAY_RELEASE_INPUTS.projectGodot),
    normalizeRelative(DEFAULT_PLAY_RELEASE_INPUTS.exportPresets),
    ...GENERATOR_SCRIPT_INPUTS,
  ]);
  const seen = new Set();
  const checked = [];
  for (const input of manifest.inputs) {
    if (typeof input?.path !== 'string' || seen.has(input.path)) {
      throw new Error('binary-only retained manifest input record contract differs.');
    }
    seen.add(input.path);
    if (!excluded.has(input.path)) checked.push(input);
  }
  for (const required of excluded) {
    if (!seen.has(required)) {
      throw new Error(
        `binary-only retained manifest input record is missing: ${required}`,
      );
    }
  }
  return { checked, excluded: [...excluded].sort() };
}

function binaryOnlyConfirmationToken({
  bundleSha256,
  galleryDigest,
  manifestDigest,
  releaseNotes,
  versionCode,
  versionName,
}) {
  const binding = sha256(canonicalJson({
    bundleSha256,
    galleryDigest,
    manifestDigest,
    mode: PLAY_BINARY_ONLY_MODE,
    releaseNotes,
    track: PLAY_BINARY_ONLY_TRACK,
    versionCode,
    versionName,
  }));
  return [
    'google-play-binary-only',
    PLAY_PACKAGE_NAME,
    versionCode,
    PLAY_BINARY_ONLY_TRACK,
    binding.slice(0, 16),
  ].join(':');
}

export function createPlayBinaryOnlyUpdatePlan({
  bundleRelative = DEFAULT_PLAY_RELEASE_INPUTS.bundle,
  configRelative = GOOGLE_PLAY_APPLY_CONFIG,
  env = process.env,
  freshnessDependencies = DEFAULT_FRESHNESS_DEPENDENCIES.bundle,
  inspectBundle = inspectAndroidBundle,
  inspectServiceAccount = inspectGoogleServiceAccount,
  outputRelative = PLAY_BINARY_ONLY_PACKAGE,
  receiptRelative = PLAY_BINARY_ONLY_RECEIPT,
  root,
  verifyPackage = verifyPlayReleasePackage,
} = {}) {
  const rootReal = assertRoot(root);
  const outputPath = resolveRepoInput(root, outputRelative, 'binary-only retained package', {
    directory: true,
  });
  const verifiedManifest = verifyPackage(outputPath, { env, root });
  const manifestContents = readStableBytes(
    resolve(outputPath, 'manifest.json'),
    'binary-only retained manifest',
  );
  let manifest;
  try {
    manifest = JSON.parse(manifestContents.toString('utf8'));
  } catch {
    throw new Error('binary-only retained manifest JSON is invalid.');
  }
  if (canonicalJson(manifest) !== canonicalJson(verifiedManifest)) {
    throw new Error('binary-only retained manifest changed after package verification.');
  }
  if (manifest.packageName !== PLAY_PACKAGE_NAME) {
    throw new Error('binary-only retained package name differs.');
  }
  // The new AAB, the current project/preset identity, and the generator
  // bytecode are verified by dedicated checks below instead of byte currency:
  // the bundle differs by design, version identity is enforced semantically
  // against the new AAB, and generator bytes cannot change retained payloads
  // that are already hash-pinned and compared to remote before any mutation.
  const { checked, excluded } = partitionManifestInputs(manifest, bundleRelative);
  verifyManifestInputsAreCurrent(root, { ...manifest, inputs: checked });
  const config = loadGooglePlayApplyPlanConfig(root, configRelative);
  const gallery = collectRetainedGallery(outputPath, manifest);
  const manifestDigest = sha256(manifestContents);

  const bundleAbsolute = resolveRepoInput(root, bundleRelative, 'binary-only AAB');
  const bundleBytes = readStableBytes(bundleAbsolute, 'binary-only AAB');
  assertBundleIsFresh(rootReal, bundleAbsolute, freshnessDependencies);
  const bundleSha256 = sha256(bundleBytes);
  if (typeof inspectBundle !== 'function') {
    throw new Error('binary-only AAB inspector is missing.');
  }
  const inspection = inspectBundle(bundleAbsolute, { env, root });
  const actual = inspection?.manifest;
  const identity = readProjectPresetIdentity(rootReal);
  const play = identity.play;
  if (
    actual?.packageName !== play.packageName
    || actual?.versionCode !== play.versionCode
    || actual?.versionName !== play.versionName
  ) {
    throw new Error(
      'binary-only AAB manifest package name, versionCode, and versionName '
      + 'differ from the Android Play preset.',
    );
  }
  if (inspection?.signing?.verified !== true) {
    throw new Error('binary-only AAB signature verification evidence is missing.');
  }
  if (inspection?.signing?.pinnedToConfiguredReleaseKey !== true) {
    throw new Error(
      'binary-only AAB signer is not pinned to the specified release keystore certificate.',
    );
  }
  const retainedVersionCode = manifest.release?.versionCode;
  const retainedVersionName = manifest.release?.versionName;
  if (
    !Number.isSafeInteger(retainedVersionCode)
    || typeof retainedVersionName !== 'string'
    || retainedVersionName === ''
  ) {
    throw new Error('binary-only retained release version contract differs.');
  }
  if (actual.versionName !== retainedVersionName) {
    throw new Error(
      `binary-only update keeps version ${retainedVersionName}: `
      + `new AAB versionName ${actual.versionName} differs.`,
    );
  }
  if (!Number.isSafeInteger(actual.versionCode) || actual.versionCode <= retainedVersionCode) {
    throw new Error(
      `binary-only versionCode ${actual.versionCode} is not strictly newer than `
      + `retained ${retainedVersionCode}.`,
    );
  }

  const credentialGate = inspectServiceAccount({ env, root });
  const blockers = [];
  if (!credentialGate.ready) {
    blockers.push(
      `Google service account blocked: ${credentialGate.reason}. `
      + 'Set GOOGLE_APPLICATION_CREDENTIALS to a mode-0600 service-account JSON outside the repository.',
    );
  }
  const plan = {
    blockers,
    bundle: {
      path: normalizeRelative(bundleRelative),
      sha256: bundleSha256,
    },
    confirmationToken: binaryOnlyConfirmationToken({
      bundleSha256,
      galleryDigest: gallery.galleryDigest,
      manifestDigest,
      releaseNotes: gallery.releaseNotes,
      versionCode: actual.versionCode,
      versionName: actual.versionName,
    }),
    credential: {
      configured: credentialGate.configured,
      ready: credentialGate.ready,
      reason: credentialGate.reason,
    },
    currencyExclusions: excluded,
    galleryDigest: gallery.galleryDigest,
    images: gallery.uploads,
    listings: gallery.listings,
    manifestDigest,
    mode: PLAY_BINARY_ONLY_MODE,
    outputPath,
    packageName: PLAY_PACKAGE_NAME,
    ready: blockers.length === 0,
    receiptPath: resolveRepoOutput(root, receiptRelative, 'binary-only update receipt'),
    root: rootReal,
    release: {
      name: `Moonlit Beacon ${actual.versionName}`,
      releaseNotes: gallery.releaseNotes,
      status: config.releaseStatus,
      track: PLAY_BINARY_ONLY_TRACK,
      versionCode: String(actual.versionCode),
      versionName: actual.versionName,
    },
    retained: {
      bundleSha256: manifest.release?.bundle?.sha256 ?? null,
      manifestDigest,
      versionCode: String(retainedVersionCode),
      versionName: retainedVersionName,
    },
    reuse: {
      decision: 'REUSE_COMMITTED_GALLERY',
      freshCaptureEvidence: false,
      galleryEvidence: PLAY_BINARY_ONLY_GALLERY_EVIDENCE,
      gallerySource: 'committed-local-package',
      nativePurchaseEvidence: 'NOT_USED_PENDING',
    },
    review: {
      changesInReviewBehavior: config.changesInReviewBehavior,
      changesNotSentForReview: !config.sendChangesForReview,
    },
  };
  return deepFreeze(plan);
}

function loadGooglePlayApplyPlanConfig(root, configRelative) {
  const config = loadGooglePlayApplyConfig(root, configRelative);
  if (config.track !== PLAY_BINARY_ONLY_TRACK) {
    throw new Error('binary-only update is allowed only on the internal track.');
  }
  if (config.changesInReviewBehavior !== 'ERROR_IF_IN_REVIEW') {
    throw new Error('binary-only update requires the ERROR_IF_IN_REVIEW contract.');
  }
  return config;
}

export function parsePlayBinaryOnlyArguments(args) {
  const result = {
    apply: false,
    bundle: DEFAULT_PLAY_RELEASE_INPUTS.bundle,
    check: false,
    config: GOOGLE_PLAY_APPLY_CONFIG,
    confirmation: null,
    help: false,
    json: false,
    package: PLAY_BINARY_ONLY_PACKAGE,
    promoteProduction: false,
    promotionConfirmation: null,
    promotionReceipt: PLAY_BINARY_ONLY_PROMOTION_RECEIPT,
    receipt: PLAY_BINARY_ONLY_RECEIPT,
    reviewConfirmation: null,
    reviewReceipt: PLAY_BINARY_ONLY_REVIEW_RECEIPT,
    submitProductionReview: false,
  };
  const seen = new Set();
  for (let index = 0; index < args.length; index += 1) {
    const argument = args[index];
    if (seen.has(argument) && argument.startsWith('--')) {
      throw new Error(`Duplicate option: ${argument}`);
    }
    seen.add(argument);
    if (argument === '--help' || argument === '-h') {
      result.help = true;
    } else if (argument === '--check') {
      result.check = true;
    } else if (argument === '--apply') {
      result.apply = true;
    } else if (argument === '--promote-production') {
      result.promoteProduction = true;
    } else if (argument === '--submit-production-review') {
      result.submitProductionReview = true;
    } else if (argument === '--json') {
      result.json = true;
    } else if (
      argument === '--package'
      || argument === '--bundle'
      || argument === '--config'
      || argument === '--receipt'
    ) {
      const value = args[index + 1];
      if (!value || value.startsWith('--')) {
        throw new Error(`${argument} requires a repository-relative path after it.`);
      }
      result[argument.slice(2)] = value;
      index += 1;
    } else if (argument === '--promotion-receipt') {
      const value = args[index + 1];
      if (!value || value.startsWith('--')) {
        throw new Error(`${argument} requires a repository-relative path after it.`);
      }
      result.promotionReceipt = value;
      index += 1;
    } else if (argument === '--review-receipt') {
      const value = args[index + 1];
      if (!value || value.startsWith('--')) {
        throw new Error(`${argument} requires a repository-relative path after it.`);
      }
      result.reviewReceipt = value;
      index += 1;
    } else if (argument === '--confirm-binary-only') {
      const value = args[index + 1];
      if (!value || value.startsWith('--')) {
        throw new Error('--confirm-binary-only requires the token --check printed.');
      }
      result.confirmation = value;
      index += 1;
    } else if (argument === '--confirm-binary-only-promotion') {
      const value = args[index + 1];
      if (!value || value.startsWith('--')) {
        throw new Error('--confirm-binary-only-promotion requires the token --check printed.');
      }
      result.promotionConfirmation = value;
      index += 1;
    } else if (argument === '--confirm-binary-only-review') {
      const value = args[index + 1];
      if (!value || value.startsWith('--')) {
        throw new Error('--confirm-binary-only-review requires the token --check printed.');
      }
      result.reviewConfirmation = value;
      index += 1;
    } else {
      throw new Error(`unsupported option: ${argument}`);
    }
  }
  if (result.help) return result;
  const modeCount = [
    result.check,
    result.apply,
    result.promoteProduction,
    result.submitProductionReview,
  ].filter(Boolean).length;
  if (modeCount > 1) {
    throw new Error(
      'Specify exactly one of --check, --apply, --promote-production, '
      + 'or --submit-production-review.',
    );
  }
  if (modeCount === 0) {
    result.check = true;
  }
  if (result.promoteProduction && result.confirmation !== null) {
    throw new Error('--promote-production uses only the --confirm-binary-only-promotion token.');
  }
  if (result.submitProductionReview && result.confirmation !== null) {
    throw new Error(
      '--submit-production-review uses only the --confirm-binary-only-review token.',
    );
  }
  if (
    (result.promoteProduction && result.reviewConfirmation !== null)
    || (result.submitProductionReview && result.promotionConfirmation !== null)
  ) {
    throw new Error('Promotion and review confirmations cannot be combined.');
  }
  if (!result.apply && result.confirmation !== null) {
    throw new Error('--confirm-binary-only can only be used with --apply.');
  }
  if (!result.promoteProduction && result.promotionConfirmation !== null) {
    throw new Error('--confirm-binary-only-promotion can only be used with --promote-production.');
  }
  if (!result.submitProductionReview && result.reviewConfirmation !== null) {
    throw new Error(
      '--confirm-binary-only-review can only be used with --submit-production-review.',
    );
  }
  if (result.apply && result.confirmation === null) {
    throw new Error('--apply requires --confirm-binary-only with the token --check printed.');
  }
  if (result.promoteProduction && result.promotionConfirmation === null) {
    throw new Error(
      '--promote-production requires --confirm-binary-only-promotion with the token --check printed.',
    );
  }
  if (result.submitProductionReview && result.reviewConfirmation === null) {
    throw new Error(
      '--submit-production-review requires --confirm-binary-only-review with the token --check printed.',
    );
  }
  return result;
}

export function assertPlayBinaryOnlyAuthorization(plan, { confirmation } = {}) {
  if (!plan.ready && plan.blockers.length > 0) {
    throw new Error(`binary-only remote update is blocked: ${plan.blockers.join(' | ')}`);
  }
  if (!plan.ready) {
    throw new Error('binary-only remote update is blocked: local check did not pass.');
  }
  if (confirmation !== plan.confirmationToken) {
    throw new Error(
      'binary-only remote confirmation token differs from the current binary and '
      + 'retained gallery. Re-run --check.',
    );
  }
  return true;
}

function releaseCarriesCode(release, versionCode) {
  const active = Array.isArray(release?.activeArtifacts)
    ? release.activeArtifacts.map((artifact) => String(artifact?.versionCode ?? ''))
    : [];
  const listed = Array.isArray(release?.versionCodes)
    ? release.versionCodes.map(String)
    : [];
  return active.includes(versionCode) || listed.includes(versionCode);
}

function assertTrackReleaseList(response, track) {
  if (!Array.isArray(response?.releases)) {
    throw new Error(`binary-only ${track} committed release list response contract differs.`);
  }
  return response.releases;
}

function parseRemoteVersionCode(value) {
  const text = typeof value === 'number' ? String(value) : value;
  if (typeof text !== 'string' || !/^[0-9]+$/u.test(text)) return null;
  const code = Number.parseInt(text, 10);
  if (!Number.isSafeInteger(code) || code < 1) return null;
  return code;
}

function collectRemoteVersionCodes(releases, track) {
  const codes = [];
  for (const release of releases) {
    if (release === null || typeof release !== 'object' || Array.isArray(release)) {
      throw new Error(`binary-only reuse refused: ${track} release entry is malformed.`);
    }
    const artifacts = release.activeArtifacts;
    if (artifacts !== undefined) {
      if (!Array.isArray(artifacts)) {
        throw new Error(`binary-only reuse refused: ${track} activeArtifacts contract differs.`);
      }
      for (const artifact of artifacts) {
        const code = parseRemoteVersionCode(artifact?.versionCode);
        if (code === null) {
          throw new Error(
            `binary-only reuse refused: ${track} activeArtifacts has a malformed versionCode entry.`,
          );
        }
        codes.push(code);
      }
    }
    const listed = release.versionCodes;
    if (listed !== undefined) {
      if (!Array.isArray(listed)) {
        throw new Error(`binary-only reuse refused: ${track} versionCodes contract differs.`);
      }
      for (const value of listed) {
        const code = parseRemoteVersionCode(value);
        if (code === null) {
          throw new Error(
            `binary-only reuse refused: ${track} versionCodes has a malformed versionCode entry.`,
          );
        }
        codes.push(code);
      }
    }
  }
  return codes;
}

// The proposed code must beat every code already committed anywhere: a
// surprise newer build on either track refuses, never downgrades.
function refuseWhenRemoteIsNewer(plan, internal, production) {
  if (!/^[0-9]+$/u.test(plan.release.versionCode ?? '')) {
    throw new Error('binary-only proposed versionCode contract differs.');
  }
  const proposed = Number.parseInt(plan.release.versionCode, 10);
  if (!Number.isSafeInteger(proposed) || proposed < 1) {
    throw new Error('binary-only proposed versionCode contract differs.');
  }
  for (const [track, releases] of [
    [PLAY_BINARY_ONLY_TRACK, internal],
    ['production', production],
  ]) {
    for (const code of collectRemoteVersionCodes(releases, track)) {
      if (proposed > code) continue;
      if (track === PLAY_BINARY_ONLY_TRACK) {
        throw new Error(
          `binary-only reuse refused: internal carries newer versionCode ${code} `
          + `than proposed ${proposed}. Not downgrading a surprise newer build.`,
        );
      }
      throw new Error(
        `binary-only reuse refused: unexpected remote track state, production carries newer `
        + `versionCode ${code} than proposed ${proposed}.`,
      );
    }
  }
}

// Immediately before any mutation, the reuse gates below must all hold: the
// current same-version release is committed on internal, the new versionCode
// appears nowhere (no duplicate, no surprise on production), and every
// retained listing and ordered image hash equals the remote gallery.
async function verifyRemoteTracksForReuse(plan, client) {
  const internal = assertTrackReleaseList(
    await client.listTrackReleases(plan.packageName, PLAY_BINARY_ONLY_TRACK),
    PLAY_BINARY_ONLY_TRACK,
  );
  const allowedStates = new Set(COMMITTED_RELEASE_LIFECYCLE_STATES);
  const retainedName = `Moonlit Beacon ${plan.retained.versionName}`;
  const retainedMatches = internal.filter((candidate) => (
    candidate?.track === PLAY_BINARY_ONLY_TRACK
    && candidate?.releaseName === retainedName
    && allowedStates.has(candidate?.releaseLifecycleState)
    && Array.isArray(candidate.activeArtifacts)
    && candidate.activeArtifacts.length === 1
    && String(candidate.activeArtifacts[0]?.versionCode ?? '')
      === plan.retained.versionCode
  ));
  if (retainedMatches.length !== 1) {
    throw new Error(
      `binary-only reuse refused: internal versionCode ${plan.retained.versionCode} `
      + `(${plan.retained.versionName}) committed release could not be re-verified. `
      + 'Exact release is not one, or lifecycle, release name, or single active '
      + 'artifact contract differs.',
    );
  }
  if (internal.some((candidate) => releaseCarriesCode(candidate, plan.release.versionCode))) {
    throw new Error(
      `binary-only reuse refused: internal already carries versionCode ${plan.release.versionCode}. `
      + 'Not attempting a duplicate code.',
    );
  }
  const production = assertTrackReleaseList(
    await client.listTrackReleases(plan.packageName, 'production'),
    'production',
  );
  if (production.some((candidate) => releaseCarriesCode(candidate, plan.release.versionCode))) {
    throw new Error(
      `binary-only reuse refused: unexpected remote track state, production already `
      + `carries versionCode ${plan.release.versionCode}.`,
    );
  }
  refuseWhenRemoteIsNewer(plan, internal, production);
  return { internalRelease: retainedMatches[0] };
}

function localImagesFor(locale, imageType, uploads) {
  return uploads
    .filter((operation) => (
      operation.language === locale && operation.imageType === imageType
    ))
    .map((operation) => operation.sha256);
}

async function verifyRemoteGalleryUnchanged(plan, client, editId, { stage }) {
  const listingsResponse = await client.listEditListings(plan.packageName, editId);
  if (!Array.isArray(listingsResponse?.listings)) {
    throw new Error(`binary-only ${stage}: remote listing list response contract differs.`);
  }
  const remoteByLanguage = new Map();
  for (const listing of listingsResponse.listings) {
    if (
      typeof listing?.language !== 'string'
      || remoteByLanguage.has(listing.language)
    ) {
      throw new Error(`binary-only ${stage}: remote listing language contract differs.`);
    }
    remoteByLanguage.set(listing.language, listing);
  }
  const remoteLanguages = [...remoteByLanguage.keys()].sort();
  const expectedLanguages = [...PLAY_LOCALES].sort();
  if (JSON.stringify(remoteLanguages) !== JSON.stringify(expectedLanguages)) {
    throw new Error(
      `binary-only ${stage}: remote listing locale set differs from the 5-language contract.`,
    );
  }
  for (const { body, language } of plan.listings) {
    const remote = remoteByLanguage.get(language);
    if (
      remote.title !== body.title
      || remote.shortDescription !== body.shortDescription
      || remote.fullDescription !== body.fullDescription
    ) {
      throw new Error(
        `binary-only ${stage}: remote ${language} listing copy differs from the retained gallery.`,
      );
    }
  }
  let verifiedImages = 0;
  for (const locale of PLAY_LOCALES) {
    for (const imageType of PLAY_BINARY_ONLY_IMAGE_TYPES) {
      const expected = localImagesFor(locale, imageType, plan.images);
      const response = await client.listEditImages(
        plan.packageName,
        editId,
        locale,
        imageType,
      );
      if (!Array.isArray(response?.images)) {
        throw new Error(
          `binary-only ${stage}: remote ${locale}/${imageType} image list response contract differs.`,
        );
      }
      const remote = response.images.map((image) => {
        if (
          typeof image?.id !== 'string'
          || image.id === ''
          || typeof image?.sha256 !== 'string'
          || !/^[0-9a-f]{64}$/u.test(image.sha256)
        ) {
          throw new Error(
            `binary-only ${stage}: remote ${locale}/${imageType} image record contract differs.`,
          );
        }
        return image.sha256;
      });
      if (
        remote.length !== expected.length
        || remote.some((digest, index) => digest !== expected[index])
      ) {
        throw new Error(
          `binary-only ${stage}: remote ${locale}/${imageType} ordered image hashes differ `
          + 'from the retained gallery.',
        );
      }
      verifiedImages += remote.length;
    }
  }
  return { verifiedImages, verifiedListings: plan.listings.length };
}

function assertExactKeys(value, keys, label) {
  if (value === null || typeof value !== 'object' || Array.isArray(value)) {
    throw new Error(`${label} must be a JSON object.`);
  }
  const actual = Object.keys(value).sort();
  const expected = [...keys].sort();
  if (JSON.stringify(actual) !== JSON.stringify(expected)) {
    throw new Error(`${label} key contract differs.`);
  }
}

function assertIsoTimestamp(value, label, { nullable = false } = {}) {
  if (nullable && value === null) return;
  if (
    typeof value !== 'string'
    || Number.isNaN(Date.parse(value))
    || new Date(value).toISOString() !== value
  ) {
    throw new Error(`binary-only receipt ${label} time is invalid.`);
  }
}

function receiptTimestamp(now, label) {
  const value = now();
  if (!(value instanceof Date) || Number.isNaN(value.valueOf())) {
    throw new Error(`${label} time provider is invalid.`);
  }
  return value.toISOString();
}

function validateBinaryOnlyReceipt(plan, receipt) {
  assertExactKeys(receipt, [
    'bundleSha256',
    'currencyExclusions',
    'galleryDigest',
    'galleryEvidence',
    'manifestDigest',
    'mode',
    'packageName',
    'retainedVersionCode',
    'schemaVersion',
    'track',
    'update',
    'versionCode',
    'versionName',
  ], 'binary-only update receipt');
  assertExactKeys(receipt.update, [
    'appliedAt',
    'committedAt',
    'editId',
    'intentCreatedAt',
    'proof',
    'state',
  ], 'binary-only update state');
  if (
    receipt.schemaVersion !== PLAY_BINARY_ONLY_RECEIPT_SCHEMA_VERSION
    || receipt.mode !== PLAY_BINARY_ONLY_MODE
    || receipt.packageName !== plan.packageName
    || receipt.track !== PLAY_BINARY_ONLY_TRACK
    || receipt.versionName !== plan.release.versionName
    || receipt.versionCode !== plan.release.versionCode
    || receipt.retainedVersionCode !== plan.retained.versionCode
    || receipt.bundleSha256 !== plan.bundle.sha256
    || receipt.manifestDigest !== plan.manifestDigest
    || receipt.galleryDigest !== plan.galleryDigest
    || receipt.galleryEvidence !== PLAY_BINARY_ONLY_GALLERY_EVIDENCE
    || JSON.stringify([...receipt.currencyExclusions].sort())
      !== JSON.stringify([...plan.currencyExclusions].sort())
  ) {
    throw new Error(
      'binary-only update receipt differs from the current binary and retained gallery.',
    );
  }
  if (!RECEIPT_STATES.includes(receipt.update.state)) {
    throw new Error('binary-only update receipt state is unknown.');
  }
  if (
    receipt.update.editId !== null
    && (typeof receipt.update.editId !== 'string' || receipt.update.editId === '')
  ) {
    throw new Error('binary-only update receipt edit id is invalid.');
  }
  if (
    receipt.update.proof !== null
    && receipt.update.proof !== 'COMMIT_RESPONSE'
    && receipt.update.proof !== 'TRACK_RELEASE'
  ) {
    throw new Error('binary-only update receipt proof kind is invalid.');
  }
  assertIsoTimestamp(receipt.update.intentCreatedAt, 'update intent');
  assertIsoTimestamp(receipt.update.committedAt, 'update commit', { nullable: true });
  assertIsoTimestamp(receipt.update.appliedAt, 'update apply', { nullable: true });
  if (
    (receipt.update.state === 'COMMITTING'
      && (receipt.update.committedAt !== null
        || receipt.update.appliedAt !== null
        || receipt.update.proof !== null))
    || (receipt.update.state === 'COMMITTED'
      && (receipt.update.committedAt === null
        || receipt.update.appliedAt !== null
        || receipt.update.proof !== 'COMMIT_RESPONSE'))
    || (receipt.update.state === 'APPLIED'
      && (receipt.update.committedAt === null
        || receipt.update.appliedAt === null
        || receipt.update.proof !== 'TRACK_RELEASE'))
  ) {
    throw new Error('binary-only update receipt state contract differs.');
  }
  return receipt;
}

export function readPlayBinaryOnlyReceipt(plan) {
  assertReceiptPath(plan.receiptPath);
  if (!existsSync(plan.receiptPath)) {
    throw new Error('binary-only update receipt is missing.');
  }
  const contents = readStableBytes(plan.receiptPath, 'binary-only update receipt');
  let parsed;
  try {
    parsed = JSON.parse(contents.toString('utf8'));
  } catch {
    throw new Error('binary-only update receipt JSON is invalid.');
  }
  return validateBinaryOnlyReceipt(plan, parsed);
}

function assertReceiptPath(path) {
  if (typeof path !== 'string' || !isAbsolute(path)) {
    throw new Error('binary-only update receipt path is not absolute.');
  }
  const parent = dirname(path);
  if (!existsSync(parent) || !lstatSync(parent).isDirectory()) {
    throw new Error('binary-only update receipt parent directory is missing.');
  }
  if (lstatSync(parent).isSymbolicLink()) {
    throw new Error('binary-only update receipt parent directory is a symbolic link.');
  }
  if (existsSync(path)) {
    const info = lstatSync(path);
    if (
      !info.isFile()
      || info.isSymbolicLink()
      || (info.mode & 0o077) !== 0
    ) {
      throw new Error('binary-only update receipt is not an owner-only regular file.');
    }
  }
  accessSync(parent, fsConstants.W_OK);
}

function atomicWriteReceipt(path, value) {
  assertReceiptPath(path);
  const temporary = `${path}.${process.pid}.${randomUUID()}.tmp`;
  let descriptor;
  let directoryDescriptor;
  try {
    descriptor = openSync(
      temporary,
      fsConstants.O_CREAT | fsConstants.O_EXCL | fsConstants.O_WRONLY,
      0o600,
    );
    writeFileSync(descriptor, `${JSON.stringify(value, null, 2)}\n`, 'utf8');
    fsyncSync(descriptor);
    closeSync(descriptor);
    descriptor = undefined;
    renameSync(temporary, path);
    directoryDescriptor = openSync(dirname(path), fsConstants.O_RDONLY);
    fsyncSync(directoryDescriptor);
  } finally {
    if (descriptor !== undefined) closeSync(descriptor);
    if (directoryDescriptor !== undefined) closeSync(directoryDescriptor);
    if (existsSync(temporary)) unlinkSync(temporary);
  }
}

// First receipt wins: link(2) publishes fully-written bytes atomically and
// fails with EEXIST when another operator won the race after the last read.
function atomicCreateReceipt(path, value) {
  assertReceiptPath(path);
  if (existsSync(path)) {
    throw new Error('binary-only update receipt already exists. Keeping the existing receipt.');
  }
  const temporary = `${path}.${process.pid}.${randomUUID()}.tmp`;
  let descriptor;
  let directoryDescriptor;
  try {
    descriptor = openSync(
      temporary,
      fsConstants.O_CREAT | fsConstants.O_EXCL | fsConstants.O_WRONLY,
      0o600,
    );
    writeFileSync(descriptor, `${JSON.stringify(value, null, 2)}\n`, 'utf8');
    fsyncSync(descriptor);
    closeSync(descriptor);
    descriptor = undefined;
    linkSync(temporary, path);
    directoryDescriptor = openSync(dirname(path), fsConstants.O_RDONLY);
    fsyncSync(directoryDescriptor);
    unlinkSync(temporary);
    fsyncSync(directoryDescriptor);
  } finally {
    if (descriptor !== undefined) closeSync(descriptor);
    if (directoryDescriptor !== undefined) closeSync(directoryDescriptor);
    if (existsSync(temporary)) unlinkSync(temporary);
  }
}

function writeValidatedReceipt(plan, receipt, write) {
  const validated = validateBinaryOnlyReceipt(plan, receipt);
  write(plan.receiptPath, validated);
  const durable = readPlayBinaryOnlyReceipt(plan);
  if (canonicalJson(durable) !== canonicalJson(validated)) {
    throw new Error('binary-only update receipt durable readback differs.');
  }
  return durable;
}

function assertMutationClient(client) {
  for (const method of [
    'insertEdit',
    'listTrackReleases',
    'listEditListings',
    'listEditImages',
    'uploadBundle',
    'updateTrack',
    'validateEdit',
    'commitEdit',
  ]) {
    if (!client || typeof client[method] !== 'function') {
      throw new Error(`binary-only Publisher client is missing ${method}.`);
    }
  }
  return true;
}

export async function applyPlayBinaryOnlyUpdatePlan(plan, {
  client,
  confirmation,
  createReceipt = atomicCreateReceipt,
  now = () => new Date(),
  writeReceipt = atomicWriteReceipt,
} = {}) {
  // Token and local gates first: a bad approval must never reach the network.
  assertPlayBinaryOnlyAuthorization(plan, { confirmation });
  assertMutationClient(client);
  if (plan.release.track !== PLAY_BINARY_ONLY_TRACK) {
    throw new Error('binary-only update is allowed only on the internal track.');
  }
  if (plan.review?.changesInReviewBehavior !== 'ERROR_IF_IN_REVIEW') {
    throw new Error('binary-only update requires the ERROR_IF_IN_REVIEW contract.');
  }
  if (plan.mode !== PLAY_BINARY_ONLY_MODE) {
    throw new Error('binary-only update plan mode differs.');
  }

  // A leftover receipt means an earlier update already reached the remote
  // API. Never start a second one from a clean slate.
  if (existsSync(plan.receiptPath)) {
    let detail;
    try {
      const existing = readPlayBinaryOnlyReceipt(plan);
      detail = `Update for this binary is already ${existing.update.state}.`;
    } catch {
      detail = 'Leftover receipt differs from the current binary and retained gallery. '
        + 'If it is a previous-binary receipt, confirm remote state and archive it separately.';
    }
    throw new Error(
      `binary-only update receipt already exists. ${detail} `
      + `First check internal versionCode ${plan.release.versionCode} status in Play Console.`,
    );
  }

  // Immutable binding: the exact bytes hashed at plan time are the bytes
  // uploaded. A rebuild or swap between --check and --apply refuses here.
  const bundlePath = resolveRepoInput(plan.root, plan.bundle.path, 'binary-only AAB');
  const bundle = readStableBytes(bundlePath, 'binary-only AAB');
  if (sha256(bundle) !== plan.bundle.sha256) {
    throw new Error('binary-only AAB differs from the immutable plan snapshot.');
  }

  await verifyRemoteTracksForReuse(plan, client);

  let receipt = writeValidatedReceipt(plan, {
    bundleSha256: plan.bundle.sha256,
    currencyExclusions: [...plan.currencyExclusions].sort(),
    galleryDigest: plan.galleryDigest,
    galleryEvidence: PLAY_BINARY_ONLY_GALLERY_EVIDENCE,
    manifestDigest: plan.manifestDigest,
    mode: PLAY_BINARY_ONLY_MODE,
    packageName: plan.packageName,
    retainedVersionCode: plan.retained.versionCode,
    schemaVersion: PLAY_BINARY_ONLY_RECEIPT_SCHEMA_VERSION,
    track: PLAY_BINARY_ONLY_TRACK,
    update: {
      appliedAt: null,
      committedAt: null,
      editId: null,
      intentCreatedAt: receiptTimestamp(now, 'update intent'),
      proof: null,
      state: 'COMMITTING',
    },
    versionCode: plan.release.versionCode,
    versionName: plan.release.versionName,
  }, createReceipt);

  let editId = null;
  let committed = false;
  try {
    const edit = await client.insertEdit(plan.packageName);
    if (typeof edit?.id !== 'string' || edit.id === '') {
      throw new Error('binary-only edit insert response has no edit id.');
    }
    editId = edit.id;
    receipt = writeValidatedReceipt(plan, {
      ...receipt,
      update: { ...receipt.update, editId },
    }, writeReceipt);

    await verifyRemoteGalleryUnchanged(plan, client, editId, {
      stage: 'pre-mutation reuse gate',
    });

    const uploaded = await client.uploadBundle(plan.packageName, editId, bundle);
    if (
      String(uploaded?.versionCode ?? '') !== plan.release.versionCode
      || typeof uploaded?.sha256 !== 'string'
      || !/^[0-9a-f]{64}$/u.test(uploaded.sha256)
      || uploaded.sha256 !== plan.bundle.sha256
    ) {
      throw new Error(
        'binary-only uploaded AAB versionCode or official hex sha256 differs from the plan.',
      );
    }
    const track = {
      releases: [{
        name: plan.release.name,
        releaseNotes: plan.release.releaseNotes,
        status: plan.release.status,
        versionCodes: [plan.release.versionCode],
      }],
      track: PLAY_BINARY_ONLY_TRACK,
    };
    const updatedTrack = await client.updateTrack(
      plan.packageName,
      editId,
      PLAY_BINARY_ONLY_TRACK,
      track,
    );
    if (
      updatedTrack?.track !== PLAY_BINARY_ONLY_TRACK
      || !Array.isArray(updatedTrack.releases)
      || !updatedTrack.releases.some((release) => (
        release?.status === plan.release.status
        && Array.isArray(release.versionCodes)
        && release.versionCodes.map(String).includes(plan.release.versionCode)
      ))
    ) {
      throw new Error('binary-only internal track response differs from the plan.');
    }
    const validatedEdit = await client.validateEdit(plan.packageName, editId);
    if (validatedEdit?.id !== editId) {
      throw new Error('binary-only edit validate response id differs.');
    }
    let committedEdit;
    try {
      committedEdit = await client.commitEdit(plan.packageName, editId, plan.review);
      if (committedEdit?.id !== editId) {
        throw new Error('commit response id differs.');
      }
    } catch (error) {
      const uncertain = new Error(
        'binary-only edit commit result is uncertain. Do not rerun until you confirm '
        + `versionCode ${plan.release.versionCode} status in Play Console. `
        + `Cause: ${error.message}`,
      );
      uncertain.binaryOnlyCommitStatus = 'uncertain';
      throw uncertain;
    }
    committed = true;
    receipt = writeValidatedReceipt(plan, {
      ...receipt,
      update: {
        ...receipt.update,
        committedAt: receiptTimestamp(now, 'update commit'),
        editId: committedEdit?.id ?? editId,
        proof: 'COMMIT_RESPONSE',
        state: 'COMMITTED',
      },
    }, writeReceipt);

    await verifyPostCommitReadback(plan, client);
    receipt = writeValidatedReceipt(plan, {
      ...receipt,
      update: {
        ...receipt.update,
        appliedAt: receiptTimestamp(now, 'update apply'),
        proof: 'TRACK_RELEASE',
        state: 'APPLIED',
      },
    }, writeReceipt);
    return {
      applied: true,
      committed: true,
      editId: receipt.update.editId,
      packageName: plan.packageName,
      retainedVersionCode: plan.retained.versionCode,
      track: PLAY_BINARY_ONLY_TRACK,
      versionCode: plan.release.versionCode,
    };
  } catch (error) {
    // An uncertain commit must never be blindly retried or discarded: the
    // edit may already be committed server-side, and the COMMITTING receipt
    // stays so the next operator confirms Play Console first.
    const uncertain = error.binaryOnlyCommitStatus === 'uncertain';
    if (editId !== null && !committed && !uncertain && typeof client.discardEdit === 'function') {
      try {
        await client.discardEdit(plan.packageName, editId);
      } catch {
        // The original failure is more actionable; an uncommitted edit expires.
      }
    }
    if (/^binary-only app commit succeeded=/u.test(error.message)) throw error;
    const status = error.binaryOnlyCommitStatus ?? (committed ? 'true' : 'false');
    throw new Error(
      `binary-only app commit succeeded=${status}, versionCode=${plan.release.versionCode}. `
      + error.message,
    );
  }
}

async function verifyPostCommitReadback(plan, client) {
  const internal = assertTrackReleaseList(
    await client.listTrackReleases(plan.packageName, PLAY_BINARY_ONLY_TRACK),
    PLAY_BINARY_ONLY_TRACK,
  );
  const allowedStates = new Set(COMMITTED_RELEASE_LIFECYCLE_STATES);
  const matches = internal.filter((candidate) => (
    candidate?.track === PLAY_BINARY_ONLY_TRACK
    && candidate?.releaseName === plan.release.name
    && allowedStates.has(candidate?.releaseLifecycleState)
    && Array.isArray(candidate.activeArtifacts)
    && candidate.activeArtifacts.length === 1
    && String(candidate.activeArtifacts[0]?.versionCode ?? '')
      === plan.release.versionCode
  ));
  if (matches.length !== 1) {
    throw new Error(
      `binary-only post-commit readback failed: internal versionCode ${plan.release.versionCode} `
      + 'exact release is not one, or lifecycle, release name, or single active '
      + 'artifact contract differs.',
    );
  }
  const readEdit = await client.insertEdit(plan.packageName);
  if (typeof readEdit?.id !== 'string' || readEdit.id === '') {
    throw new Error('binary-only post-commit read edit response has no edit id.');
  }
  try {
    await verifyRemoteGalleryUnchanged(plan, client, readEdit.id, {
      stage: 'post-commit unchanged-media readback',
    });
  } finally {
    if (typeof client.discardEdit === 'function') {
      try {
        await client.discardEdit(plan.packageName, readEdit.id);
      } catch {
        // Readback comparison result stands; a read-only edit expires.
      }
    }
  }
  return { release: matches[0] };
}

export function formatPlayBinaryOnlyReport(plan, { mode = 'check' } = {}) {
  const status = plan.ready ? 'ready' : 'blocked';
  return [
    `Google Play binary-only internal update ${mode === 'check' ? 'local check' : 'result'}: ${status}`,
    `Package: ${plan.packageName}`,
    `Version: ${plan.release.versionName} `
      + `(${plan.retained.versionCode} → ${plan.release.versionCode}) / ${plan.release.track}`,
    `Listings/images reused: ${plan.listings.length}/${plan.images.length} `
      + `(gallery ${plan.galleryDigest.slice(0, 16)}, ${PLAY_BINARY_ONLY_GALLERY_EVIDENCE})`,
    `Bundle: ${plan.bundle.sha256.slice(0, 16)} (fresh, pinned to configured release key)`,
    'Metadata, images, prices, products, production, reviews: untouched',
    ...(plan.blockers.length > 0
      ? plan.blockers.map((blocker) => `Blocked: ${blocker}`)
      : [
        `Binary-only apply confirmation: --confirm-binary-only ${plan.confirmationToken}`,
      ]),
  ].join('\n');
}
