/**
 * Verify one variant's complete iOS export inputs: the static library
 * (with the entry symbol), the staged Firebase frameworks (FirebaseAuth
 * present), the staged privacy bundles (the exact required set, each
 * with its manifest), the Godot import exclusion next to each staged
 * set, and the extension descriptor. This is the link-time contract:
 * the Xcode project needs every one of these, not just the standalone
 * archive, and the editor must skip the native products on reimport.
 * `nm` follows the artifact verifiers' injection pattern for tests.
 */
export function verifyIosExportInputs({ root, variant, nm } = {}) {
  const checks = [];
  const artifacts = identityArtifactPaths(root);
  const lib = variant === 'debug' ? artifacts.iosDebugLib : artifacts.iosReleaseLib;
  if (!existsSync(lib)) {
    checks.push(`missing static library ${lib}; run --build-ios --${variant} first`);
  } else {
    const verdict = verifyIosArtifact(lib, { nm });
    for (const check of verdict.checks) checks.push(check);
  }
  const frameworksDir = identityIosFrameworksDir(root, variant);
  let frameworkNames = [];
  try {
    frameworkNames = readdirSync(frameworksDir, { withFileTypes: true })
      .filter((entry) => entry.name.endsWith('.framework'))
      .map((entry) => entry.name);
  } catch {
    frameworkNames = [];
  }
  if (frameworkNames.length === 0) {
    checks.push(`no staged frameworks under ${frameworksDir}; run --build-ios --${variant} first`);
  } else {
    for (const want of ['FirebaseAuth.framework', 'GoogleSignIn.framework']) {
      if (!frameworkNames.includes(want)) {
        checks.push(`staged frameworks under ${frameworksDir} lack ${want}`);
      }
    }
  }
  if (!existsSync(join(frameworksDir, IOS_STAGED_IMPORT_EXCLUSION))) {
    checks.push(
      `no Godot import exclusion under ${frameworksDir}; the editor would import native SDK products — re-run --build-ios --${variant}`,
    );
  }
  const resourcesDir = identityIosResourcesDir(root, variant);
  let stagedBundles = [];
  try {
    stagedBundles = readdirSync(resourcesDir, { withFileTypes: true })
      .filter((entry) => entry.name.endsWith('.bundle'))
      .map((entry) => entry.name)
      .sort();
  } catch {
    stagedBundles = [];
  }
  const missing = IDENTITY_REQUIRED_PRIVACY_BUNDLES.filter((want) => !stagedBundles.includes(want));
  const extra = stagedBundles.filter((name) => !IDENTITY_REQUIRED_PRIVACY_BUNDLES.includes(name));
  if (missing.length > 0 || extra.length > 0 || stagedBundles.length === 0) {
    checks.push(
      `staged resources under ${resourcesDir} are not the required set `
      + `(missing: ${missing.join(', ') || 'none'}; `
      + `unexpected: ${extra.join(', ') || 'none'})`,
    );
  }
  for (const name of stagedBundles) {
    if (!IDENTITY_REQUIRED_PRIVACY_BUNDLES.includes(name)) continue;
    if (!existsSync(join(resourcesDir, name, 'PrivacyInfo.xcprivacy'))) {
      checks.push(`staged ${name} lacks PrivacyInfo.xcprivacy; re-run --build-ios --${variant}`);
    }
  }
  if (!existsSync(join(resourcesDir, IOS_STAGED_IMPORT_EXCLUSION))) {
    checks.push(
      `no Godot import exclusion under ${resourcesDir}; the editor would import native SDK products — re-run --build-ios --${variant}`,
    );
  }
  const descriptor = join(root, 'apps/game/addons/moonlit-identity/ios/moonlit_identity.gdextension.ios');
  if (!existsSync(descriptor)) {
    checks.push(`missing extension descriptor ${descriptor}`);
  }
  return { ok: checks.length === 0, checks };
}

/**
 * Fetch the pinned Firebase iOS SDK via CocoaPods, then build its static
 * frameworks for arm64 physical devices (Debug + Release) and link-tree
 * them for the bridge compile and the export. Network use happens only
 * when the director runs this; tests inject `spawn` and stage fake
 * framework output dirs.
 */
export function fetchIosDeps({ root, outDir, spawn = spawnSync } = {}) {
  const dir = outDir ?? identityBuildDirs(root).iosDeps;
  renderIosDepsProject({ root, outDir: dir });
  const podsDir = join(dir, 'Pods');
  const agreement = checkPodsTargetAgreement(
    readFileSync(join(dir, 'Podfile'), 'utf8'),
    readFileSync(join(dir, 'FirebasePods.xcodeproj/project.pbxproj'), 'utf8'),
  );
  if (!agreement.ok) {
    return { ok: false, podsDir, output: '', checks: [agreement.error] };
  }
  const install = runBridgeBuild({ command: 'pod', args: ['install'], cwd: dir, spawn });
  if (!install.ok) {
    return {
      ok: false,
      podsDir,
      output: install.output,
      checks: [`pod install failed (exit ${install.status})`],
    };
  }
  const outputs = [install.output];
  const aggregate = podsAggregateTarget(agreement.target);
  const aggregateProduct = podsAggregateProductName(agreement.target);
  const buildDir = join(dir, 'Build');
  for (const config of ['Debug', 'Release']) {
    const built = runBridgeBuild({
      command: 'xcodebuild',
      args: [
        '-project', 'Pods/Pods.xcodeproj',
        '-target', aggregate,
        '-sdk', 'iphoneos',
        '-arch', 'arm64',
        '-configuration', config,
        `SYMROOT=${buildDir}`,
        'CODE_SIGNING_ALLOWED=NO',
        '-quiet',
        'build',
      ],
      cwd: dir,
      spawn,
    });
    outputs.push(built.output);
    if (!built.ok) {
      return {
        ok: false,
        podsDir,
        output: outputs.join('\n').trim(),
        checks: [`xcodebuild ${config} framework build failed (exit ${built.status})`],
      };
    }
  }
  const tree = buildFirebaseLinkTree({ depsRoot: dir, excludeProducts: [aggregateProduct] });
  return {
    ok: tree.ok,
    podsDir,
    linkDir: tree.linkDir,
    output: outputs.join('\n').trim(),
    checks: tree.checks,
    variants: tree.variants,
  };
}

