/**
 * Copy one variant's discovered frameworks into the addon export staging
 * dir. Symlinks resolve to their real framework dirs first; internal
 * framework symlinks (Headers, Modules) are preserved as links.
 */
export function stageIosFrameworks({ depsRoot, variant, destDir }) {
  const link = firebaseLinkPaths(join(depsRoot, 'Pods'));
  if (!existsSync(link.flagsFile)) {
    return {
      ok: false,
      staged: [],
      checks: [`missing link tree ${link.flagsFile}; run --fetch-deps --platform ios first`],
    };
  }
  let flags = null;
  try {
    flags = JSON.parse(readFileSync(link.flagsFile, 'utf8'));
  } catch {
    flags = null;
  }
  const entry = flags?.variants?.[variant];
  if (!entry || !Array.isArray(entry.frameworks) || typeof entry.frameworks_dir !== 'string') {
    return {
      ok: false,
      staged: [],
      checks: [`link tree ${link.flagsFile} has no ${variant} variant; re-run --fetch-deps`],
    };
  }
  rmSync(destDir, { recursive: true, force: true });
  mkdirSync(destDir, { recursive: true });
  const staged = [];
  for (const name of entry.frameworks) {
    let real = '';
    try {
      real = realpathSync(join(entry.frameworks_dir, `${name}.framework`));
    } catch {
      return {
        ok: false,
        staged,
        checks: [`framework ${name} vanished from ${entry.frameworks_dir}; re-run --fetch-deps`],
      };
    }
    cpSync(real, join(destDir, `${name}.framework`), { recursive: true });
    staged.push(name);
  }
  for (const want of ['FirebaseAuth', 'GoogleSignIn']) {
    if (!staged.includes(want)) {
      return {
        ok: false,
        staged,
        checks: [`link tree ${link.flagsFile} staged no ${want}; re-run --fetch-deps`],
      };
    }
  }
  writeIosStagingImportExclusion(destDir);
  return { ok: true, staged, checks: [] };
}

