// Public identity configuration for the MoonlitIdentity native bridge.
//
// The Android plugin needs the Google OAuth web client id (the Credential
// Manager Google ID option plus the Play Games v2 server auth code flow)
// and the Play Games application id. The iOS plugin needs the iOS OAuth
// client id (GoogleSignIn configuration plus the reversed-client-ID
// callback URL scheme the export stamps into Info.plist). Both natives
// need the Firebase public client config
// (project id, sender id, per-platform API key and app id) so they can
// initialize Firebase from staged values instead of throwing on a missing
// google-services bundle. These are PUBLIC identifiers: they ship inside
// every exported Firebase app. They arrive from ignored configuration
// (live environment or repo-root `.env`, never committed) and are staged
// into `res://moonlit_identity.cfg` only for the duration of an export.
//
// The Android Apple browser flow needs no staged client value: its Service
// ID/key material stays server-side in the Firebase console. The staged
// Apple flag only records that the director configured it, so the app
// offers the provider truthfully. The Apple service id itself is a
// server-side value (web OAuth flows); the native iOS Apple sheet needs
// the App ID entitlement plus Firebase client config, not a services id,
// so it is optional here and never staged into the app. Private material
// — OAuth client secrets, the Apple .p8 key — never passes through here.
// It stays in provider/server settings and the director's own export
// machine. Nothing in this module prints a value: reports name the
// variable and its presence/length only.

