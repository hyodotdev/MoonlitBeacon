/**
 * Read the checked-out revision of a godot-cpp directory without running
 * git (no subprocess, no path interpolation): `.git/HEAD` either holds a
 * detached SHA (what `git clone --branch <tag>` leaves) or a ref whose
 * file holds the SHA. Worktree pointer files (`.git` holding
 * `gitdir: <path>`) resolve too. Returns the 40-hex SHA or null.
 */
export function readGitHeadRevision(dir) {
  try {
    const dotGit = join(dir, '.git');
    let gitDir = dotGit;
    let headPath = join(gitDir, 'HEAD');
    if (!existsSync(headPath)) {
      const pointer = readFileSync(dotGit, 'utf8');
      const match = /^gitdir:\s*(.+?)\s*$/.exec(pointer);
      if (!match) return null;
      gitDir = match[1].startsWith('/') ? match[1] : join(dir, match[1]);
      headPath = join(gitDir, 'HEAD');
    }
    const head = readFileSync(headPath, 'utf8').trim();
    if (/^[0-9a-f]{40}$/.test(head)) return head;
    const ref = /^ref:\s*(\S+)$/.exec(head);
    if (!ref) return null;
    const sha = readFileSync(join(gitDir, ref[1]), 'utf8').trim();
    return /^[0-9a-f]{40}$/.test(sha) ? sha : null;
  } catch {
    return null;
  }
}

