export const GOOGLE_CLIENT_ID_ENV = 'MOONLIT_PLAY_SERVER_CLIENT_ID';
export const GOOGLE_APP_ID_ENV = 'MOONLIT_PLAY_APP_ID';
export const GOOGLE_IOS_CLIENT_ID_ENV = 'MOONLIT_GOOGLE_IOS_CLIENT_ID';
export const APPLE_ANDROID_ENABLED_ENV = 'MOONLIT_APPLE_ANDROID_ENABLED';
export const APPLE_IOS_ENABLED_ENV = 'MOONLIT_APPLE_IOS_ENABLED';
export const APPLE_SERVICE_ID_ENV = 'MOONLIT_APPLE_SERVICE_ID';
export const FIREBASE_PROJECT_ENV = 'MOONLIT_FIREBASE_PROJECT_ID';
export const FIREBASE_SENDER_ENV = 'MOONLIT_FIREBASE_SENDER_ID';
export const FIREBASE_ANDROID_KEY_ENV = 'MOONLIT_FIREBASE_ANDROID_API_KEY';
export const FIREBASE_ANDROID_APP_ENV = 'MOONLIT_FIREBASE_ANDROID_APP_ID';
export const FIREBASE_IOS_KEY_ENV = 'MOONLIT_FIREBASE_IOS_API_KEY';
export const FIREBASE_IOS_APP_ENV = 'MOONLIT_FIREBASE_IOS_APP_ID';

// A Google OAuth client id always ends this way; anything else is a
// paste of the wrong value (an API key, a secret, a bundle id). The same
// shape holds for the OAuth web client id (Android) and the iOS client id.
const GOOGLE_CLIENT_ID_SHAPE = /^[0-9]+-[A-Za-z0-9_-]+\.apps\.googleusercontent\.com$/;
// An Apple acknowledgement is a plain boolean flag, one per platform. Only
// true/1 enables the provider (mirrored by the GDScript gate); false/0 is
// well-formed but not ready, anything else is a malformed value.
const APPLE_FLAG_SHAPE = /^(true|false|1|0)$/i;
const APPLE_ENABLED_SHAPE = /^(true|1)$/i;
// The Play Games application id is the numeric APP_ID from Play Console
// (Play Games Services setup). The Android export stamps it into the app
// manifest; the bridge refuses provider calls without it (fail-closed).
const PLAY_APP_ID_SHAPE = /^[0-9]{4,20}$/;
// An Apple Sign in with Apple service id is a reverse-DNS string.
const APPLE_SERVICE_ID_SHAPE = /^[A-Za-z0-9-]+(\.[A-Za-z0-9-]+)+$/;
// Firebase public client config shapes (same values google-services.json and
// GoogleService-Info.plist carry; all public, all shipped in app binaries).
const FIREBASE_PROJECT_SHAPE = /^[a-z0-9-]+$/;
const FIREBASE_SENDER_SHAPE = /^[0-9]+$/;
const FIREBASE_API_KEY_SHAPE = /^AIza[A-Za-z0-9_-]{30,}$/;
const FIREBASE_APP_ID_SHAPE = /^1:[0-9]+:(android|ios):[A-Za-z0-9]+$/;

const GENERATED_HEADER =
  '; Generated by scripts/build-player-identity.mjs --install for one export.\n' +
  '; Do not commit. Remove with --clean after the export.\n';

export function identityConfigPaths(root) {
  return {
    // Read by the GDScript wrapper at `res://moonlit_identity.cfg`.
    installed: join(root, 'apps/game/moonlit_identity.cfg'),
    // Staging copy under the ignored builds/ dir for inspection.
    staged: join(root, 'builds/.moonlit_identity.cfg-stage'),
  };
}

export function emptyIdentityResolution() {
  const slot = (env) => ({ env, present: false, length: 0, value: '' });
  return {
    google: slot(GOOGLE_CLIENT_ID_ENV),
    playAppId: slot(GOOGLE_APP_ID_ENV),
    googleIosClient: slot(GOOGLE_IOS_CLIENT_ID_ENV),
    appleAndroidEnabled: slot(APPLE_ANDROID_ENABLED_ENV),
    appleIosEnabled: slot(APPLE_IOS_ENABLED_ENV),
    appleService: slot(APPLE_SERVICE_ID_ENV),
    firebaseProject: slot(FIREBASE_PROJECT_ENV),
    firebaseSender: slot(FIREBASE_SENDER_ENV),
    firebaseAndroidKey: slot(FIREBASE_ANDROID_KEY_ENV),
    firebaseAndroidApp: slot(FIREBASE_ANDROID_APP_ENV),
    firebaseIosKey: slot(FIREBASE_IOS_KEY_ENV),
    firebaseIosApp: slot(FIREBASE_IOS_APP_ENV),
  };
}

/** Read public identifiers from the environment. Values stay in the object. */
export function resolvePublicIdentityConfig({ env = process.env } = {}) {
  const resolution = emptyIdentityResolution();
  for (const slot of Object.values(resolution)) {
    const raw = typeof env[slot.env] === 'string' ? env[slot.env].trim() : '';
    slot.value = raw;
    slot.present = raw.length > 0;
    slot.length = raw.length;
  }
  return resolution;
}

function checkSlot(slot, shape, want, missing, errors) {
  if (!slot.present) {
    missing.push(slot.env);
    return;
  }
  if (!shape.test(slot.value)) {
    errors.push(`${slot.env} is not ${want}.`);
  }
}

/**
 * Validate one platform's public config. Returns
 * `{ ok, missing, errors, notes, providers }` where `missing`/`errors`
 * name variables only, never values. `ok` means full readiness (every
 * provider on the platform); partial configs still install and stage,
 * and the per-provider `providers` map plus the runtime capability gates
 * keep each provider truthful on its own. The Apple service id is
 * server-side only and never required here.
 */
export function validateIdentityConfig(resolution, platform) {
  const missing = [];
  const errors = [];
  const notes = [];
  const wantAndroid = platform === 'android' || platform === 'all';
  const wantIos = platform === 'ios' || platform === 'all';
  if (!['android', 'ios', 'all'].includes(platform)) {
    throw new Error(`Unknown identity platform "${platform}". Use android, ios, or all.`);
  }
  if (wantAndroid) {
    checkSlot(
      resolution.google,
      GOOGLE_CLIENT_ID_SHAPE,
      'a Google OAuth web client id (want "<numeric>-<suffix>.apps.googleusercontent.com")',
      missing,
      errors,
    );
    checkSlot(
      resolution.playAppId,
      PLAY_APP_ID_SHAPE,
      'a numeric Play Games application id (the APP_ID from Play Console)',
      missing,
      errors,
    );
    checkAppleFlag(resolution.appleAndroidEnabled, 'Android', missing, errors);
    checkFirebaseSlots(resolution, 'android', missing, errors);
  }
  if (wantIos) {
    checkSlot(
      resolution.googleIosClient,
      GOOGLE_CLIENT_ID_SHAPE,
      'a Google OAuth iOS client id (want "<numeric>-<suffix>.apps.googleusercontent.com", from the Firebase console iOS app config)',
      missing,
      errors,
    );
    checkAppleFlag(resolution.appleIosEnabled, 'iOS', missing, errors);
    checkFirebaseSlots(resolution, 'ios', missing, errors);
  }
  // Server-side note only: a present-but-malformed service id is flagged so
  // a paste mistake is visible, but it never blocks native readiness.
  if (resolution.appleService.present
    && !APPLE_SERVICE_ID_SHAPE.test(resolution.appleService.value)) {
    notes.push(
      `${APPLE_SERVICE_ID_ENV} is not a reverse-DNS service id ` +
        '(want something like "com.example.game.signin"). ' +
        'Server-side only; native sign-in does not need it.',
    );
  }
  return {
    ok: missing.length === 0 && errors.length === 0,
    missing,
    errors,
    notes,
    providers: providerReadiness(resolution, platform),
  };
}

function checkAppleFlag(slot, platform, missing, errors) {
  if (slot.present && !APPLE_FLAG_SHAPE.test(slot.value)) {
    errors.push(
      `${slot.env} is not a boolean flag (want "true" once the Apple provider setup is acknowledged for ${platform}).`,
    );
    return;
  }
  // Absent, "false", or "0" all mean the same thing: the Apple setup is
  // not acknowledged, so the provider is not ready — without blocking
  // Google or guest play.
  if (!slot.present || !APPLE_ENABLED_SHAPE.test(slot.value)) {
    missing.push(slot.env);
  }
}

/**
 * Per-provider readiness for one platform request: `{ <platform>:
 * { <provider>: { ready, missing } } }`, naming variables only. A provider
 * is ready when its platform Firebase config and its own staged keys are
 * all well-formed; every other provider gates independently of it.
 */
export function providerReadiness(resolution, platform) {
  const valid = (slot, shape) => slot.present && shape.test(slot.value);
  const firebaseMissing = (which) => {
    const absent = [];
    const keySlot = which === 'android'
      ? resolution.firebaseAndroidKey
      : resolution.firebaseIosKey;
    const appSlot = which === 'android'
      ? resolution.firebaseAndroidApp
      : resolution.firebaseIosApp;
    if (!valid(resolution.firebaseProject, FIREBASE_PROJECT_SHAPE)) {
      absent.push(resolution.firebaseProject.env);
    }
    if (!valid(resolution.firebaseSender, FIREBASE_SENDER_SHAPE)) {
      absent.push(resolution.firebaseSender.env);
    }
    if (!valid(keySlot, FIREBASE_API_KEY_SHAPE)) absent.push(keySlot.env);
    if (!valid(appSlot, FIREBASE_APP_ID_SHAPE)) absent.push(appSlot.env);
    return absent;
  };
  const googleWebMissing = valid(resolution.google, GOOGLE_CLIENT_ID_SHAPE)
    ? []
    : [resolution.google.env];
  const out = {};
  const appleFlagReady = (slot) => slot.present
    && APPLE_ENABLED_SHAPE.test(slot.value);
  if (platform === 'android' || platform === 'all') {
    const base = firebaseMissing('android');
    const androidAppleReady = appleFlagReady(resolution.appleAndroidEnabled);
    const playReady = valid(resolution.playAppId, PLAY_APP_ID_SHAPE);
    const providers = {
      google: [...base, ...googleWebMissing],
      play_games: [...base, ...googleWebMissing],
      apple: [...base],
    };
    if (!playReady) providers.play_games.push(resolution.playAppId.env);
    if (!androidAppleReady) {
      providers.apple.push(resolution.appleAndroidEnabled.env);
    }
    out.android = {};
    for (const [name, absent] of Object.entries(providers)) {
      out.android[name] = { ready: absent.length === 0, missing: absent };
    }
  }
  if (platform === 'ios' || platform === 'all') {
    const base = firebaseMissing('ios');
    const iosClientMissing = valid(
      resolution.googleIosClient,
      GOOGLE_CLIENT_ID_SHAPE,
    ) ? [] : [resolution.googleIosClient.env];
    const iosAppleMissing = appleFlagReady(resolution.appleIosEnabled)
      ? [] : [resolution.appleIosEnabled.env];
    out.ios = {
      google: {
        ready: base.length === 0 && iosClientMissing.length === 0,
        missing: [...base, ...iosClientMissing],
      },
      apple: {
        ready: base.length === 0 && iosAppleMissing.length === 0,
        missing: [...base, ...iosAppleMissing],
      },
    };
  }
  return out;
}

function checkFirebaseSlots(resolution, platform, missing, errors) {
  checkSlot(
    resolution.firebaseProject,
    FIREBASE_PROJECT_SHAPE,
    'a Firebase project id (lowercase letters, digits, hyphens)',
    missing,
    errors,
  );
  checkSlot(
    resolution.firebaseSender,
    FIREBASE_SENDER_SHAPE,
    'a numeric Firebase sender id',
    missing,
    errors,
  );
  const keySlot = platform === 'android'
    ? resolution.firebaseAndroidKey
    : resolution.firebaseIosKey;
  const appSlot = platform === 'android'
    ? resolution.firebaseAndroidApp
    : resolution.firebaseIosApp;
  checkSlot(
    keySlot,
    FIREBASE_API_KEY_SHAPE,
    'a Firebase API key (want "AIza..." from the Firebase console app config)',
    missing,
    errors,
  );
  checkSlot(
    appSlot,
    FIREBASE_APP_ID_SHAPE,
    `a Firebase ${platform} app id (want "1:<sender>:${platform}:<suffix>")`,
    missing,
    errors,
  );
}

/**
 * Render a preflight report with no values in it. Safe to paste anywhere.
 * Presence and length only; the one thing a value's length can leak is how
 * long the value is, which is the point (empty vs set).
 */
export function formatPreflightReport(resolution, { platform = 'all' } = {}) {
  const verdict = validateIdentityConfig(resolution, platform);
  const lines = ['MoonlitIdentity preflight', `platform: ${platform}`];
  for (const slot of Object.values(resolution)) {
    const tag = slot === resolution.appleService ? ' (server-side, optional)' : '';
    lines.push(
      slot.present
        ? `${slot.env}: set (${slot.length} chars)${tag}`
        : `${slot.env}: MISSING${tag}`,
    );
  }
  for (const [which, providers] of Object.entries(verdict.providers)) {
    for (const [name, state] of Object.entries(providers)) {
      lines.push(
        state.ready
          ? `provider ${which}/${name}: READY`
          : `provider ${which}/${name}: NOT READY (missing ${state.missing.join(', ')})`,
      );
    }
  }
  if (verdict.missing.length > 0) {
    lines.push(`missing: ${verdict.missing.join(', ')}`);
    lines.push('Unready providers report not_configured; ready providers and guest play are unaffected.');
  }
  for (const error of verdict.errors) lines.push(`error: ${error}`);
  for (const note of verdict.notes) lines.push(`note: ${note}`);
  lines.push(verdict.ok ? 'result: READY' : 'result: NOT READY');
  return `${lines.join('\n')}\n`;
}

/**
 * Scrub accidental secret material from free text before printing. Public
 * client identifiers are masked too: reports must stay name-only even when
 * a caller pastes a value where a name belongs.
 */
export function redactIdentitySecrets(text) {
  return String(text)
    .replace(
      /[0-9]+-[A-Za-z0-9_-]+\.apps\.googleusercontent\.com/g,
      '[google-client-id]',
    )
    .replace(/openiap-kit_sk_[A-Za-z0-9_-]+/g, '[iapkit-secret]')
    .replace(
      /-----BEGIN PRIVATE KEY-----[\s\S]*?-----END PRIVATE KEY-----/g,
      '[private-key]',
    );
}

export function renderIdentityConfigFile(resolution) {
  const flag = (slot) => (slot.present && APPLE_ENABLED_SHAPE.test(slot.value) ? 'true' : '');
  const lines = [GENERATED_HEADER.trimEnd(), ''];
  lines.push('[google]');
  lines.push(`server_client_id="${resolution.google.value}"`);
  lines.push(`play_app_id="${resolution.playAppId.value}"`);
  lines.push(`ios_client_id="${resolution.googleIosClient.value}"`);
  lines.push('');
  lines.push('[apple]');
  lines.push(`android_enabled="${flag(resolution.appleAndroidEnabled)}"`);
  lines.push(`ios_enabled="${flag(resolution.appleIosEnabled)}"`);
  lines.push('');
  lines.push('[firebase]');
  lines.push(`project_id="${resolution.firebaseProject.value}"`);
  lines.push(`sender_id="${resolution.firebaseSender.value}"`);
  lines.push(`android_api_key="${resolution.firebaseAndroidKey.value}"`);
  lines.push(`android_app_id="${resolution.firebaseAndroidApp.value}"`);
  lines.push(`ios_api_key="${resolution.firebaseIosKey.value}"`);
  lines.push(`ios_app_id="${resolution.firebaseIosApp.value}"`);
  lines.push('');
  return `${lines.join('\n')}\n`;
}

/**
 * Dry-run preflight: validate and report, write nothing. Returns the report
 * plus the verdict so entry scripts can set the exit code.
 */
export function dryRunIdentityPreflight({ env = process.env, platform = 'all' } = {}) {
  const resolution = resolvePublicIdentityConfig({ env });
  const report = formatPreflightReport(resolution, { platform });
  const verdict = validateIdentityConfig(resolution, platform);
  return { report, ok: verdict.ok };
}

/** Write the staged + installed config files. The caller validated first. */
export function installIdentityConfig({ root, resolution }) {
  const paths = identityConfigPaths(root);
  const body = renderIdentityConfigFile(resolution);
  mkdirSync(dirname(paths.staged), { recursive: true });
  mkdirSync(dirname(paths.installed), { recursive: true });
  const temp = `${paths.installed}.tmp`;
  writeFileSync(temp, body, { encoding: 'utf8', mode: 0o600 });
  renameSync(temp, paths.installed);
  writeFileSync(paths.staged, body, { encoding: 'utf8', mode: 0o600 });
  return paths;
}

export function cleanIdentityConfig({ root }) {
  const paths = identityConfigPaths(root);
  const removed = [];
  for (const path of [paths.installed, `${paths.installed}.tmp`, paths.staged]) {
    if (existsSync(path)) {
      rmSync(path, { force: true });
      removed.push(path);
    }
  }
  return { paths, removed };
}

export function readInstalledIdentityConfig(root) {
  const { installed } = identityConfigPaths(root);
  if (!existsSync(installed)) return null;
  return readFileSync(installed, 'utf8');
}

