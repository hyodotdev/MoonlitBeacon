/**
 * The exact compiler argv fragments the SCons bridge compile must pass for
 * one variant, derived from the fetched flags file. `-F` and `-I` carry
 * their directories in the same argv item so paths with spaces stay
 * intact; the SCons template constructs these same items (pinned by
 * test) because SCons FRAMEWORKPATH never reached the compile command.
 * Returns `{ ok, flags, checks }`; loud when the variant is absent.
 */
export function iosCompileFlags({ flagsFile, variant, moduleCacheDir }) {
  let flags = null;
  try {
    flags = JSON.parse(readFileSync(flagsFile, 'utf8'));
  } catch {
    return { ok: false, flags: [], checks: [`cannot read link tree ${flagsFile}`] };
  }
  const entry = flags?.variants?.[variant];
  if (!entry || typeof entry.headers !== 'string' || typeof entry.frameworks_dir !== 'string'
    || !Array.isArray(entry.frameworks)) {
    return { ok: false, flags: [], checks: [`link tree ${flagsFile} has no ${variant} variant`] };
  }
  for (const want of ['FirebaseAuth', 'GoogleSignIn']) {
    if (!entry.frameworks.includes(want)) {
      return {
        ok: false,
        flags: [],
        checks: [`link tree ${flagsFile} lists no ${want} for ${variant}`],
      };
    }
  }
  return {
    ok: true,
    checks: [],
    flags: [
      `-F${entry.frameworks_dir}`,
      `-I${entry.headers}`,
      '-fmodules',
      '-fcxx-modules',
      `-fmodules-cache-path=${moduleCacheDir}`,
    ],
  };
}

/**
 * Report Android build prerequisites. Never fetches, never prints values.
 * `{ env, root, exec }` are injectable for tests.
 */
export function checkAndroidBuildPrereqs({ env = process.env, root, exec = defaultExec } = {}) {
  const missing = [];
  const notes = [];
  const java = javaMajorVersion({ exec });
  if (java === null) {
    missing.push('java (JDK 17+, for Android Gradle Plugin 8.5.0)');
  } else if (java < IDENTITY_PINS.java) {
    missing.push(`java ${IDENTITY_PINS.java}+ (found major ${java})`);
  }
  const sdkRoot = typeof env.ANDROID_SDK_ROOT === 'string' ? env.ANDROID_SDK_ROOT.trim()
    : typeof env.ANDROID_HOME === 'string' ? env.ANDROID_HOME.trim()
      : '';
  if (!sdkRoot) {
    missing.push('ANDROID_SDK_ROOT (Android SDK location)');
  } else if (!existsSync(sdkRoot)) {
    missing.push(`Android SDK directory (${sdkRoot} not found)`);
  }
  const gradleFound = gradleMajorMinor({ exec });
  if (gradleFound === null) {
    notes.push(
      'No system gradle on PATH; the build invokes the system binary so it '
      + 'can verify the exact version. Install '
      + `Gradle ${IDENTITY_PINS.gradle}, or generate the wrapper jar with it `
      + '(see gradle-wrapper.properties.tmpl) for reproducible re-runs.',
    );
    missing.push(`gradle ${IDENTITY_PINS.gradle} (system binary)`);
  } else if (gradleFound !== IDENTITY_PINS.gradle) {
    missing.push(`gradle ${IDENTITY_PINS.gradle} (found ${gradleFound})`);
  }
  for (const [from] of ANDROID_TEMPLATE_FILES) {
    const template = join(root, 'apps/game/addons/moonlit-identity/android', from);
    if (!existsSync(template)) missing.push(`template ${from}`);
  }
  const gdap = join(root, 'apps/game/addons/moonlit-identity/android/MoonlitIdentity.gdap');
  if (!existsSync(gdap)) {
    missing.push('MoonlitIdentity.gdap');
  } else {
    const body = readFileSync(gdap, 'utf8');
    for (const pin of [
      `play-services-games-v2:${IDENTITY_PINS.playServicesGamesV2}`,
      `firebase-auth:${IDENTITY_PINS.firebaseAuthAndroid}`,
      `androidx.credentials:credentials:${IDENTITY_PINS.credentialsAndroid}`,
      `androidx.credentials:credentials-play-services-auth:${IDENTITY_PINS.credentialsPlayServicesAuth}`,
      `com.google.android.libraries.identity.googleid:googleid:${IDENTITY_PINS.googleIdAndroid}`,
      `org.jetbrains.kotlinx:kotlinx-coroutines-android:${IDENTITY_PINS.coroutinesAndroid}`,
    ]) {
      if (!body.includes(pin)) missing.push(`gdap pin ${pin}`);
    }
  }
  return { ok: missing.length === 0, missing, notes };
}

/**
 * Report iOS build prerequisites. Never fetches, never prints values.
 * Physical device only (arm64); no simulator slice is built.
 */
export function checkIosBuildPrereqs({ env = process.env, root, exec = defaultExec } = {}) {
  const missing = [];
  const notes = [];
  if (!commandExists('xcodebuild', exec)) missing.push('xcodebuild (Xcode command line tools)');
  if (!commandExists('scons', exec)) missing.push('scons (pip/conda install, then re-run)');
  if (!commandExists('pod', exec)) {
    missing.push(`pod (CocoaPods ${IDENTITY_PINS.cocoapods}.x; verified ${IDENTITY_PINS.cocoapodsVerified})`);
  } else {
    const podVersion = podMajorMinor({ exec });
    if (podVersion === null) {
      notes.push(`could not read pod --version; verified with CocoaPods ${IDENTITY_PINS.cocoapodsVerified}`);
    } else if (podVersion !== IDENTITY_PINS.cocoapods) {
      missing.push(`cocoapods ${IDENTITY_PINS.cocoapods}.x (found ${podVersion})`);
    }
  }
  const godotCpp = typeof env.GODOT_CPP === 'string' ? env.GODOT_CPP.trim() : '';
  if (!godotCpp) {
    missing.push(`GODOT_CPP (pinned godot-cpp checkout, tag ${IDENTITY_PINS.godotCppTag})`);
    notes.push(
      `Fetch it with: git clone --branch ${IDENTITY_PINS.godotCppTag} --depth 1 `
      + 'https://github.com/godotengine/godot-cpp',
    );
  } else if (!existsSync(join(godotCpp, 'SConstruct'))) {
    missing.push(`GODOT_CPP checkout (${godotCpp} has no SConstruct)`);
  } else {
    const head = readGitHeadRevision(godotCpp);
    if (head === null) {
      notes.push(
        `could not read a git revision from GODOT_CPP (${godotCpp}); want tag `
        + `${IDENTITY_PINS.godotCppTag} (${IDENTITY_PINS.godotCppRev.slice(0, 12)}).`,
      );
    } else if (head !== IDENTITY_PINS.godotCppRev) {
      missing.push(
        `godot-cpp ${IDENTITY_PINS.godotCppTag} revision `
        + `${IDENTITY_PINS.godotCppRev.slice(0, 12)} (found ${head.slice(0, 12)})`,
      );
    }
  }
  const godotCppLib = typeof env.GODOT_CPP_LIB === 'string' ? env.GODOT_CPP_LIB.trim() : '';
  if (!godotCppLib) {
    missing.push('GODOT_CPP_LIB (prebuilt godot-cpp iOS arm64 archives)');
  } else {
    const debugLib = join(godotCppLib, 'libgodot-cpp.ios.template_debug.arm64.a');
    const releaseLib = join(godotCppLib, 'libgodot-cpp.ios.template_release.arm64.a');
    if (!existsSync(debugLib) || !existsSync(releaseLib)) {
      missing.push('godot-cpp iOS arm64 archives (build both template targets first)');
      notes.push(
        'Build them with: cd $GODOT_CPP && scons platform=ios arch=arm64 '
        + `target=template_debug ios_min_version=${IDENTITY_PINS.iosMinVersion} -j4 `
        + '&& scons platform=ios arch=arm64 '
        + `target=template_release ios_min_version=${IDENTITY_PINS.iosMinVersion} -j4`,
      );
    }
  }
  const podsDir = typeof env.FIREBASE_PODS_DIR === 'string' && env.FIREBASE_PODS_DIR.trim()
    ? env.FIREBASE_PODS_DIR.trim()
    : defaultFirebasePodsDir(root);
  const linkFile = firebaseLinkPaths(podsDir).flagsFile;
  let linkOk = false;
  if (existsSync(linkFile)) {
    try {
      const flags = JSON.parse(readFileSync(linkFile, 'utf8'));
      const variants = flags?.variants ?? {};
      linkOk = ['debug', 'release'].every(
        (variant) => Array.isArray(variants[variant]?.frameworks)
          && variants[variant].frameworks.includes('FirebaseAuth')
          && variants[variant].frameworks.includes('GoogleSignIn'),
      );
    } catch {
      linkOk = false;
    }
  }
  if (!linkOk) {
    missing.push(
      `identity iOS SDK device frameworks (FirebaseAuth ${IDENTITY_PINS.firebaseAuthIos} `
      + `+ GoogleSignIn ${IDENTITY_PINS.googleSignInIos}; `
      + `expected a link tree at ${linkFile})`,
    );
    notes.push(
      'Fetch them with: node scripts/build-player-identity.mjs --fetch-deps --platform ios',
    );
  }
  for (const name of ['SConstruct.tmpl', 'Podfile.tmpl', 'xcodeproj/project.pbxproj.tmpl']) {
    const template = join(root, 'apps/game/addons/moonlit-identity/ios', name);
    if (!existsSync(template)) missing.push(`template ${name}`);
  }
  return { ok: missing.length === 0, missing, notes };
}

/**
 * Exact environment allowlist for bridge build children. `load-env` loads
 * release/server secrets into process.env, and native compilation only needs
 * build paths and tool locations, so children receive this list and nothing
 * else: no MOONLIT_*, OPENIAP_*, ASC_*, service-account, or secret names.
 * (The repo's other scripts inherit the full env; that pattern is wrong here
 * because Gradle/SCons child output can echo environment into build logs.)
 */
export const BUILD_CHILD_ENV_ALLOWLIST = [
  'PATH',
  'HOME',
  'USER',
  'LOGNAME',
  'TMPDIR',
  'TEMP',
  'TMP',
  'LANG',
  'LC_ALL',
  'JAVA_HOME',
  'ANDROID_SDK_ROOT',
  'ANDROID_HOME',
  'ANDROID_NDK_ROOT',
  'ANDROID_NDK_HOME',
  'GRADLE_USER_HOME',
  'GODOT_CPP',
  'GODOT_CPP_LIB',
  'FIREBASE_PODS_DIR',
  'DEVELOPER_DIR',
  'SystemRoot',
  'NUMBER_OF_PROCESSORS',
];

export function sanitizedBuildEnv(env = process.env) {
  const clean = {};
  for (const name of BUILD_CHILD_ENV_ALLOWLIST) {
    if (typeof env[name] === 'string' && env[name].length > 0) clean[name] = env[name];
  }
  return clean;
}

export function formatBuildPrereqReport(kind, result) {
  const lines = [`MoonlitIdentity ${kind} build prerequisites`];
  if (result.missing.length === 0) {
    lines.push('all prerequisites present');
  } else {
    lines.push('missing:');
    for (const item of result.missing) lines.push(`  - ${item}`);
  }
  for (const note of result.notes) lines.push(`note: ${note}`);
  lines.push(result.ok ? 'result: READY TO BUILD' : 'result: NOT READY');
  return `${lines.join('\n')}\n`;
}

/**
 * Run a bridge build command. `spawn` is injectable for tests; output is
 * redacted before it is returned, and the child receives only the build env
 * allowlist. The caller renders templates and checks prerequisites first.
 */
export function runBridgeBuild({
  command, args, cwd, env = process.env, spawn = spawnSync,
}) {
  const result = spawn(command, args, {
    cwd,
    encoding: 'utf8',
    env: sanitizedBuildEnv(env),
    maxBuffer: 16 * 1024 * 1024,
  });
  const output = redactIdentitySecrets(
    `${result.stdout ?? ''}\n${result.stderr ?? ''}`.trim(),
  );
  return { ok: result.status === 0, status: result.status ?? 1, output };
}

function defaultExecFile(command, args, options = {}) {
  return execFileSync(command, args, {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
    ...options,
  });
}

/**
 * Cap for `nm` symbol output. The merged Firebase bridge archive reports
 * ~5.9 MB of defined symbols, which overflows execFileSync's 1 MiB default
 * (ENOBUFS) but fits comfortably here. The bound stays explicit so a runaway
 * tool cannot grow memory without limit.
 */
export const NM_SYMBOL_BUFFER_BYTES = 16 * 1024 * 1024;

/** Read defined-symbol names via Xcode nm with a bounded output buffer. */
export function readLibSymbols(path, execFile = defaultExecFile) {
  return String(execFile('nm', ['-gUj', path], { maxBuffer: NM_SYMBOL_BUFFER_BYTES }));
}

/**
 * Classify an `nm` failure so the report distinguishes a missing tool from a
 * failed command, a buffer overflow, and (downstream) a missing entry symbol.
 */
export function describeNmFailure(error) {
  if (error?.code === 'ENOENT') {
    return 'could not read symbols (Xcode nm not found)';
  }
  if (error?.code === 'ENOBUFS') {
    return 'could not read symbols (nm output exceeded the 16 MiB cap)';
  }
  if (typeof error?.status === 'number') {
    return `could not read symbols (nm failed with exit ${error.status})`;
  }
  return 'could not read symbols (need Xcode nm)';
}

/** Verify an AAR: manifest + classes present, plugin registration inside. */
export function verifyAndroidArtifact(aarPath, { listZip, readZipEntry } = {}) {
  if (!existsSync(aarPath)) {
    return { ok: false, checks: [`missing artifact ${aarPath}`] };
  }
  // Structured argv, never a shell string: artifact paths cannot inject.
  const list = listZip ?? ((path) => String(defaultExecFile('unzip', ['-l', path])));
  const read = readZipEntry ?? ((path, entry) => String(
    defaultExecFile('unzip', ['-p', path, entry]),
  ));
  const checks = [];
  let entries = '';
  try {
    entries = list(aarPath);
  } catch {
    return { ok: false, checks: ['could not list the AAR (need unzip)'] };
  }
  if (!entries.includes('AndroidManifest.xml')) checks.push('AAR lacks AndroidManifest.xml');
  if (!entries.includes('classes.jar')) checks.push('AAR lacks classes.jar');
  if (checks.length === 0) {
    try {
      const manifest = read(aarPath, 'AndroidManifest.xml');
      if (!manifest.includes('org.godotengine.plugin.v2.MoonlitIdentity')) {
        checks.push('manifest lacks the MoonlitIdentity plugin registration');
      }
      if (!manifest.includes('dev.moonlitbeacon.identity.MoonlitIdentityPlugin')) {
        checks.push('manifest lacks the plugin class name');
      }
      // AAR manifests ship as text XML (like the vendored IAP AAR); when
      // the entry reads as text, parse it instead of only grepping it. A
      // binary-compiled manifest skips the parse but keeps the checks above.
      if (/^\uFEFF?\s*<(?:\?xml|manifest)/.test(manifest)) {
        const parsed = checkXmlWellFormed(manifest, 'AndroidManifest.xml');
        if (!parsed.ok) checks.push(`manifest is not well-formed: ${parsed.error}`);
      }
    } catch {
      checks.push('could not read the AAR manifest (need unzip)');
    }
  }
  return { ok: checks.length === 0, checks };
}

/** Verify a static lib: the GDExtension entry symbol must be exported. */
export function verifyIosArtifact(libPath, { nm } = {}) {
  if (!existsSync(libPath)) {
    return { ok: false, checks: [`missing artifact ${libPath}`] };
  }
  const runNm = nm ?? readLibSymbols;
  let symbols = '';
  try {
    symbols = runNm(libPath);
  } catch (error) {
    return { ok: false, checks: [describeNmFailure(error)] };
  }
  const checks = [];
  if (!symbols.includes('moonlit_identity_ios_entry')) {
    checks.push('library lacks the moonlit_identity_ios_entry symbol');
  }
  return { ok: checks.length === 0, checks };
}

// ---------------------------------------------------------------------------
// Strict XML well-formedness checks. The Android plugin manifest broke a
// real Gradle build (SAX: "--" inside a comment), so templates are parsed
// here, not grepped. A small tokenizer plus element stack covering the full
// well-formedness contract: prolog, comments (with the double-hyphen rule),
// processing instructions, CDATA, DOCTYPE, elements, quoted attributes,
// entity references, exactly one root, nothing trailing.
// ---------------------------------------------------------------------------

/**
 * Parse `text` as XML. Returns `{ ok: true }` or `{ ok: false, error }`
 * where `error` is `label:line: reason`. No dependencies, no network.
 */
export function checkXmlWellFormed(text, label = 'xml') {
  const src = String(text);
  const fail = (pos, why) => ({
    ok: false,
    error: `${label}:${src.slice(0, pos).split('\n').length}: ${why}`,
  });
  let i = 0;
  if (src.charCodeAt(0) === 0xfeff) i = 1;
  const isWs = (ch) => ch === ' ' || ch === '\t' || ch === '\r' || ch === '\n';
  const skipWs = () => {
    while (i < src.length && isWs(src[i])) i += 1;
  };
  const readName = () => {
    const match = /^[A-Za-z_:][A-Za-z0-9_.:-]*/.exec(src.slice(i));
    if (!match) return '';
    i += match[0].length;
    return match[0];
  };
  // Entity reference at src[amp] === '&'; returns the index past it or -1.
  const entityEnd = (amp) => {
    const end = src.indexOf(';', amp + 1);
    if (end < 0 || end - amp > 12) return -1;
    const body = src.slice(amp + 1, end);
    if (body === 'amp' || body === 'lt' || body === 'gt'
      || body === 'quot' || body === 'apos') {
      return end + 1;
    }
    if (/^#[0-9]+$/.test(body) || /^#x[0-9A-Fa-f]+$/.test(body)) return end + 1;
    return -1;
  };
  const skipComment = () => {
    const end = src.indexOf('-->', i + 4);
    if (end < 0) return fail(i, 'unterminated comment');
    if (src.slice(i + 4, end).includes('--')) {
      return fail(i, 'The string "--" is not permitted within comments');
    }
    i = end + 3;
    return null;
  };
  const skipPi = (allowDecl) => {
    const end = src.indexOf('?>', i + 2);
    if (end < 0) return fail(i, 'unterminated processing instruction');
    const target = /^<\?([A-Za-z_][A-Za-z0-9_.-]*)/.exec(src.slice(i));
    if (!target) return fail(i, 'malformed processing instruction');
    if (/^xml$/i.test(target[1]) && !allowDecl) {
      return fail(i, 'xml declaration is only allowed in the prolog');
    }
    i = end + 2;
    return null;
  };
  const skipDoctype = () => {
    i += 9; // Past '<!DOCTYPE'.
    let depth = 0;
    let quote = '';
    for (;;) {
      if (i >= src.length) return fail(i, 'unterminated DOCTYPE');
      const ch = src[i];
      if (quote !== '') {
        if (ch === quote) quote = '';
      } else if (ch === '"' || ch === "'") {
        quote = ch;
      } else if (ch === '[') {
        depth += 1;
      } else if (ch === ']') {
        depth -= 1;
      } else if (ch === '>' && depth === 0) {
        i += 1;
        return null;
      }
      i += 1;
    }
  };
  // Comments, PIs, DOCTYPE, whitespace between markup. Returns a failure or
  // null. The XML declaration itself is consumed by the driver, not here.
  const skipMisc = () => {
    for (;;) {
      skipWs();
      if (src.startsWith('<!--', i)) {
        const bad = skipComment();
        if (bad) return bad;
      } else if (src.startsWith('<?', i)) {
        const bad = skipPi(false);
        if (bad) return bad;
      } else if (src.startsWith('<!DOCTYPE', i)
        && (i + 9 >= src.length || isWs(src[i + 9]))) {
        const bad = skipDoctype();
        if (bad) return bad;
      } else {
        return null;
      }
    }
  };
  const readAttributeValue = (attr, tag) => {
    const quote = src[i];
    if (quote !== '"' && quote !== "'") {
      return fail(i, `unquoted attribute ${attr} in <${tag}>`);
    }
    i += 1;
    for (;;) {
      if (i >= src.length) return fail(i, `unterminated attribute ${attr}`);
      if (src[i] === quote) {
        i += 1;
        return null;
      }
      if (src[i] === '<') {
        return fail(i, `"${'<'}" is not allowed inside attribute ${attr}`);
      }
      if (src[i] === '&') {
        const end = entityEnd(i);
        if (end < 0) return fail(i, `bad entity reference in attribute ${attr}`);
        i = end;
      } else {
        i += 1;
      }
    }
  };
  const readElement = () => {
    // src[i] === '<' and not a closing tag.
    i += 1;
    const tag = readName();
    if (!tag) return fail(i, 'expected an element name');
    for (;;) {
      skipWs();
      if (src.startsWith('/>', i)) {
        i += 2;
        return null;
      }
      if (src[i] === '>') {
        i += 1;
        break;
      }
      if (i >= src.length) return fail(i, `unterminated start tag <${tag}>`);
      const attr = readName();
      if (!attr) return fail(i, `expected an attribute name in <${tag}>`);
      skipWs();
      if (src[i] !== '=') return fail(i, `expected "=" after attribute ${attr}`);
      i += 1;
      skipWs();
      const bad = readAttributeValue(attr, tag);
      if (bad) return bad;
    }
    for (;;) {
      const lt = src.indexOf('<', i);
      if (lt < 0) return fail(i, `unterminated element <${tag}>`);
      let amp = src.indexOf('&', i);
      while (amp >= 0 && amp < lt) {
        const end = entityEnd(amp);
        if (end < 0) return fail(amp, 'bad entity reference in text');
        amp = src.indexOf('&', end);
      }
      i = lt;
      if (src.startsWith('</', i)) {
        i += 2;
        const close = readName();
        if (close !== tag) {
          return fail(i, `mismatched close tag </${close}> for <${tag}>`);
        }
        skipWs();
        if (src[i] !== '>') return fail(i, `expected ">" to close </${close}>`);
        i += 1;
        return null;
      }
      if (src.startsWith('<!--', i)) {
        const bad = skipComment();
        if (bad) return bad;
      } else if (src.startsWith('<![CDATA[', i)) {
        const end = src.indexOf(']]>', i + 9);
        if (end < 0) return fail(i, 'unterminated CDATA section');
        i = end + 3;
      } else if (src.startsWith('<?', i)) {
        const bad = skipPi(false);
        if (bad) return bad;
      } else if (src.startsWith('<!', i)) {
        return fail(i, 'declarations are not allowed inside elements');
      } else {
        const nested = readElement();
        if (nested) return nested;
      }
    }
  };

  skipWs();
  if (/^<\?xml[ \t\r\n]/.test(src.slice(i))) {
    const end = src.indexOf('?>', i + 2);
    if (end < 0) return fail(i, 'unterminated xml declaration');
    if (!/version\s*=\s*["']1\.[01]["']/.test(src.slice(i, end))) {
      return fail(i, 'xml declaration lacks version="1.0"');
    }
    i = end + 2;
  }
  let bad = skipMisc();
  if (bad) return bad;
  if (i >= src.length) return fail(i, 'missing root element');
  if (!src.startsWith('<', i) || src.startsWith('</', i)) {
    return fail(i, 'expected the root element');
  }
  bad = readElement();
  if (bad) return bad;
  bad = skipMisc();
  if (bad) return bad;
  if (i < src.length) return fail(i, 'content after the root element');
  return { ok: true };
}

// ---------------------------------------------------------------------------
// Xcode project template checks. CocoaPods 1.16.2 target inspection crashed
// on the first dummy project (`TypeError - no implicit conversion of nil
// into String`); the offline probe pinned the cause to missing PBXProject
// path keys, so the template carries the full canonical key set and this
// validator pins every load-bearing key and reference.
// ---------------------------------------------------------------------------

/**
 * Structurally validate an Xcode project template: every object parses,
 * every reference resolves, the project carries the keys target inspection
 * needs, and the named target (default: the Podfile target) is a static
 * library with Debug+Release configurations. Returns `{ ok, checks }`.
 */
export function checkPbxprojTemplate(text, { target } = {}) {
  const checks = [];
  const src = String(text);
  const objects = new Map();
  for (const line of src.split('\n')) {
    const entry = /^\s*([0-9A-F]{24})(?: \/\*.*?\*\/)? = \{(.*)\};\s*$/.exec(line);
    if (!entry) continue;
    const isa = /isa = ([A-Za-z]+);/.exec(entry[2]);
    objects.set(entry[1], { isa: isa ? isa[1] : '', body: entry[2] });
  }
  if (objects.size === 0) return { ok: false, checks: ['no project objects parsed'] };
  const refsOf = (body) => [...body.matchAll(/\b[0-9A-F]{24}\b/g)].map((m) => m[0]);
  const root = /rootObject = ([0-9A-F]{24})/.exec(src);
  if (!root) return { ok: false, checks: ['missing rootObject'] };
  const project = objects.get(root[1]);
  if (!project || project.isa !== 'PBXProject') {
    return { ok: false, checks: ['rootObject is not a PBXProject'] };
  }
  for (const key of ['buildConfigurationList', 'mainGroup', 'targets',
    'productRefGroup', 'projectDirPath', 'projectRoot',
    'compatibilityVersion', 'developmentRegion', 'knownRegions']) {
    if (!new RegExp(`${key} =`).test(project.body)) {
      checks.push(`PBXProject lacks ${key}`);
    }
  }
  if (!/TargetAttributes =/.test(project.body)) {
    checks.push('PBXProject attributes lack TargetAttributes');
  }
  for (const [id, obj] of objects) {
    for (const ref of refsOf(obj.body)) {
      if (!objects.has(ref)) checks.push(`dangling reference ${ref} from ${id}`);
    }
  }
  const configNames = (listId, label) => {
    const list = objects.get(listId);
    if (!list || list.isa !== 'XCConfigurationList') {
      checks.push(`${label} is not an XCConfigurationList`);
      return [];
    }
    const ids = refsOf(list.body);
    const names = [];
    for (const id of ids) {
      const config = objects.get(id);
      if (!config || config.isa !== 'XCBuildConfiguration') {
        checks.push(`${label} references non-configuration ${id}`);
        continue;
      }
      const name = /(?:^|; )name = (\w+);/.exec(config.body);
      if (name) names.push(name[1]);
    }
    for (const want of ['Debug', 'Release']) {
      if (!names.includes(want)) checks.push(`${label} lacks a ${want} configuration`);
    }
    const fallback = /defaultConfigurationName = (\w+);/.exec(list.body);
    if (!fallback) {
      checks.push(`${label} lacks defaultConfigurationName`);
    } else if (!names.includes(fallback[1])) {
      checks.push(`${label} default ${fallback[1]} matches no configuration`);
    }
    return ids;
  };
  const projectLists = refsOf(project.body);
  const projectListId = projectLists.find((id) => {
    const obj = objects.get(id);
    return obj?.isa === 'XCConfigurationList';
  });
  if (!projectListId) {
    checks.push('PBXProject has no build configuration list');
  } else {
    configNames(projectListId, 'project configuration list');
  }
  const mainGroup = objects.get((/mainGroup = ([0-9A-F]{24})/.exec(project.body) ?? [])[1]);
  if (!mainGroup || mainGroup.isa !== 'PBXGroup') {
    checks.push('PBXProject mainGroup is not a PBXGroup');
  }
  const nativeTargets = [...objects.entries()]
    .filter(([, obj]) => obj.isa === 'PBXNativeTarget');
  if (nativeTargets.length === 0) checks.push('project has no native target');
  const targetNameOf = (obj) => /(?:^|; )name = ([^;]+);/.exec(obj.body)?.[1]?.trim();
  const wanted = target ?? (nativeTargets[0] ? targetNameOf(nativeTargets[0][1]) : undefined);
  const picked = nativeTargets.find(([, obj]) => targetNameOf(obj) === wanted)
    ?? nativeTargets[0];
  if (target && !nativeTargets.some(([, obj]) => targetNameOf(obj) === target)) {
    checks.push(`project has no target named ${target}`);
  }
  if (picked) {
    const body = picked[1].body;
    if (!/productType = "com\.apple\.product-type\.library\.static";/.test(body)) {
      checks.push('identity pods target is not a static library');
    }
    const listId = (/buildConfigurationList = ([0-9A-F]{24})/.exec(body) ?? [])[1];
    if (!listId) {
      checks.push('identity pods target has no build configuration list');
    } else {
      const ids = configNames(listId, 'target configuration list');
      for (const id of ids) {
        const config = objects.get(id);
        if (!config || config.isa !== 'XCBuildConfiguration') continue;
        if (!/SDKROOT = iphoneos;/.test(config.body)) {
          checks.push(`target configuration ${id} lacks SDKROOT = iphoneos`);
        }
        if (!/IPHONEOS_DEPLOYMENT_TARGET = /.test(config.body)) {
          checks.push(`target configuration ${id} lacks IPHONEOS_DEPLOYMENT_TARGET`);
        }
        if (/OTHER_LDFLAGS =/.test(config.body)) {
          checks.push(`target configuration ${id} sets OTHER_LDFLAGS (overrides the Pods xcconfig)`);
        }
      }
    }
    const product = (/productReference = ([0-9A-F]{24})/.exec(body) ?? [])[1];
    const productObj = product ? objects.get(product) : undefined;
    if (!productObj || productObj.isa !== 'PBXFileReference') {
      checks.push('identity pods target has no product file reference');
    }
    if (!/buildPhases = \([^)]/.test(body)) {
      checks.push('identity pods target has no build phases');
    }
  }
  return { ok: checks.length === 0, checks };
}
