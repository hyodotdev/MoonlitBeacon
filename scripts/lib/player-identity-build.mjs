export function javaMajorVersion({ exec = defaultExec } = {}) {
  try {
    const output = String(exec('java -version 2>&1'));
    const match = output.match(/version "(\d+)(?:\.(\d+))?/);
    if (!match) return null;
    // "1.8" style reports major in the second group; modern "17" in the first.
    return match[1] === '1' ? Number(match[2]) : Number(match[1]);
  } catch {
    return null;
  }
}

function commandExists(name, exec) {
  try {
    exec(`command -v ${name}`);
    return true;
  } catch {
    return false;
  }
}

/** Parse `gradle --version` into "major.minor" (e.g. "8.7"), or null. */
