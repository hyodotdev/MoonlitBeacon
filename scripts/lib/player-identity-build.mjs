/**
 * Copy one variant's discovered privacy bundles into the addon export
 * staging dir, byte for byte. The staged set must equal the required
 * set exactly: a missing or extra bundle fails rather than shipping a
 * wrong compliance set. Manifests are copied, never read or rewritten.
 */
export function stageIosResources({ depsRoot, variant, destDir }) {
  const link = firebaseLinkPaths(join(depsRoot, 'Pods'));
  if (!existsSync(link.flagsFile)) {
    return {
      ok: false,
      staged: [],
      checks: [`missing link tree ${link.flagsFile}; run --fetch-deps --platform ios first`],
    };
  }
  let flags = null;
  try {
    flags = JSON.parse(readFileSync(link.flagsFile, 'utf8'));
  } catch {
    flags = null;
  }
  const entry = flags?.variants?.[variant];
  if (!entry || !Array.isArray(entry.resources)
    || typeof entry.resource_sources !== 'object' || entry.resource_sources === null) {
    return {
      ok: false,
      staged: [],
      checks: [`link tree ${link.flagsFile} has no ${variant} resources; re-run --fetch-deps`],
    };
  }
  const missing = IDENTITY_REQUIRED_PRIVACY_BUNDLES.filter((want) => !entry.resources.includes(want));
  const extra = entry.resources.filter((name) => !IDENTITY_REQUIRED_PRIVACY_BUNDLES.includes(name));
  if (missing.length > 0 || extra.length > 0) {
    return {
      ok: false,
      staged: [],
      checks: [
        `link tree ${link.flagsFile} resources are not the required set `
        + `(missing: ${missing.join(', ') || 'none'}; `
        + `unexpected: ${extra.join(', ') || 'none'}); re-run --fetch-deps`,
      ],
    };
  }
  rmSync(destDir, { recursive: true, force: true });
  mkdirSync(destDir, { recursive: true });
  const staged = [];
  for (const name of entry.resources) {
    const source = entry.resource_sources[name];
    if (typeof source !== 'string') {
      return {
        ok: false,
        staged,
        checks: [`link tree ${link.flagsFile} records no source for ${name}; re-run --fetch-deps`],
      };
    }
    let real = '';
    try {
      real = realpathSync(source);
    } catch {
      return {
        ok: false,
        staged,
        checks: [`resource ${name} vanished from ${source}; re-run --fetch-deps`],
      };
    }
    cpSync(real, join(destDir, name), { recursive: true });
    staged.push(name);
  }
  writeIosStagingImportExclusion(destDir);
  return { ok: true, staged, checks: [] };
}

