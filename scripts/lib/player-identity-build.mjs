/**
 * Walk one Pods configuration output dir for products with the given
 * filename suffix (frameworks, privacy bundles). CocoaPods nests each
 * pod's products under its own target dir, so the search recurses.
 * Bounds: depth 3, 64 products, never descends into symlinked dirs.
 * Returns `{ ok, found, checks }` where `found` maps the product name
 * (suffix stripped) to its exact path relative to `configDir`. Names in
 * `exclude` are skipped; the same name at two distinct paths fails
 * loudly rather than guessing.
 */
function walkConfigProducts(configDir, suffix, { exclude = [] } = {}) {
  const checks = [];
  try {
    readdirSync(configDir, { withFileTypes: true });
  } catch {
    return {
      ok: false,
      found: new Map(),
      checks: [`missing framework output dir ${configDir}`],
    };
  }
  const found = new Map();
  const poisoned = new Set();
  const MAX_DEPTH = 3;
  const MAX_PRODUCTS = 64;
  const visit = (dir, rel, depth) => {
    let entries = [];
    try {
      entries = readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }
    for (const entry of entries) {
      if (!entry.name.endsWith(suffix)) {
        if (depth < MAX_DEPTH && entry.isDirectory() && !entry.isSymbolicLink()) {
          visit(join(dir, entry.name), rel ? join(rel, entry.name) : entry.name, depth + 1);
        }
        continue;
      }
      if (!entry.isDirectory() && !entry.isSymbolicLink()) continue;
      const name = entry.name.slice(0, -suffix.length);
      if (exclude.includes(name) || poisoned.has(name)) continue;
      const at = rel ? join(rel, entry.name) : entry.name;
      if (found.has(name)) {
        if (found.get(name) !== at) {
          checks.push(
            `ambiguous ${entry.name}: found at both ${found.get(name)} and ${at} `
            + `under ${configDir}; refusing to guess`,
          );
          found.delete(name);
          poisoned.add(name);
        }
        continue;
      }
      found.set(name, at);
    }
  };
  visit(configDir, '', 0);
  if (found.size + poisoned.size > MAX_PRODUCTS) {
    return {
      ok: false,
      found: new Map(),
      checks: [`refusing to link ${found.size + poisoned.size} products (cap ${MAX_PRODUCTS})`],
    };
  }
  if (checks.length > 0) {
    return { ok: false, found: new Map(), checks };
  }
  return { ok: true, found, checks: [] };
}

/**
 * List the frameworks a Pods build produced for one configuration.
 * Returns `{ ok, frameworks, paths, checks }` where `paths` maps each
 * framework name to its exact bundle path relative to `configDir`; those
 * real paths flow into the link tree verbatim. Names in `exclude` (the
 * aggregate scaffolding product) are skipped. The bridge compiles against
 * both FirebaseAuth and GoogleSignIn, so either one missing — or without
 * its ObjC-visible umbrella header — fails loudly.
 */
export function discoverFirebaseFrameworks(configDir, { exclude = [] } = {}) {
  const walked = walkConfigProducts(configDir, '.framework', { exclude });
  if (!walked.ok) {
    return { ok: false, frameworks: [], paths: {}, checks: walked.checks };
  }
  const frameworks = [...walked.found.keys()].sort();
  const paths = Object.fromEntries([...walked.found.entries()].sort());
  const checks = [];
  for (const want of ['FirebaseAuth', 'GoogleSignIn']) {
    if (!frameworks.includes(want)) {
      checks.push(
        `no ${want}.framework under ${configDir} `
        + `(found: ${frameworks.join(', ') || 'none'})`,
      );
    }
  }
  if (checks.length > 0) {
    return { ok: false, frameworks, paths, checks };
  }
  for (const want of ['FirebaseAuth', 'GoogleSignIn']) {
    const umbrella = join(configDir, paths[want], 'Headers', `${want}.h`);
    if (!existsSync(umbrella)) {
      checks.push(
        `${want}.framework lacks Headers/${want}.h at ${umbrella}; `
        + 'the pods frameworks build did not produce ObjC-visible headers',
      );
    }
  }
  if (checks.length > 0) {
    return { ok: false, frameworks, paths, checks };
  }
  return { ok: true, frameworks, paths, checks: [] };
}

/**
 * List the SDK privacy-resource bundles a Pods build produced for one
 * configuration. Every discovered `*.bundle` must carry its
 * `PrivacyInfo.xcprivacy` (a bundle without one fails loudly), and the
 * discovered set must equal `expected` exactly: a missing bundle means
 * an incomplete SDK build, an extra one means the SDK contents moved
 * under the pin — both refuse silently shipping the wrong compliance
 * set. Returns `{ ok, resources, paths, checks }` with exact relative
 * bundle paths; manifests are never read, rewritten, or fabricated.
 */
export function discoverFirebaseResources(
  configDir,
  { expected = IDENTITY_REQUIRED_PRIVACY_BUNDLES } = {},
) {
  const walked = walkConfigProducts(configDir, '.bundle');
  if (!walked.ok) {
    return { ok: false, resources: [], paths: {}, checks: walked.checks };
  }
  const resources = [...walked.found.keys()]
    .map((name) => `${name}.bundle`)
    .sort();
  const paths = Object.fromEntries(
    [...walked.found.entries()]
      .map(([name, rel]) => [`${name}.bundle`, rel])
      .sort(),
  );
  const checks = [];
  for (const want of expected) {
    if (!resources.includes(want)) {
      checks.push(`missing required resource ${want} under ${configDir}`);
    }
  }
  for (const extra of resources) {
    if (!expected.includes(extra)) {
      checks.push(
        `unexpected resource ${extra} under ${configDir}; bless the new SDK set deliberately`,
      );
    }
  }
  if (checks.length === 0) {
    for (const name of resources) {
      const manifest = join(configDir, paths[name], 'PrivacyInfo.xcprivacy');
      if (!existsSync(manifest)) {
        checks.push(`resource ${name} lacks PrivacyInfo.xcprivacy at ${manifest}`);
      }
    }
  }
  if (checks.length > 0) {
    return { ok: false, resources, paths, checks };
  }
  return { ok: true, resources, paths, checks: [] };
}

/**
 * Build the MoonlitLink tree from finished Pods framework builds: per-config
 * `Frameworks/` symlinks plus a `Headers/<Pod>` symlink forest so the
 * bridge compiles with one `-I` and one `-F` per config, and a
 * `firebase-flags.json` the SCons build and the export staging read.
 * Framework symlinks target the exact discovered bundle paths (nested
 * `<Pod>/<Pod>.framework` in the real roots), recorded verbatim in
 * `framework_sources`; privacy bundles are discovered the same way and
 * recorded in `resource_sources`. Nothing here assumes a CocoaPods
 * layout.
 */
export function buildFirebaseLinkTree({ depsRoot, excludeProducts = [] }) {
  const link = firebaseLinkPaths(join(depsRoot, 'Pods'));
  const checks = [];
  const frameworksByConfig = {};
  const resourcesByConfig = {};
  for (const config of ['Debug', 'Release']) {
    const configDir = join(link.buildDir, `${config}-iphoneos`);
    const found = discoverFirebaseFrameworks(configDir, { exclude: excludeProducts });
    if (!found.ok) {
      for (const check of found.checks) checks.push(`${config}: ${check}`);
    } else {
      frameworksByConfig[config.toLowerCase()] = found;
    }
    const resources = discoverFirebaseResources(configDir);
    if (!resources.ok) {
      for (const check of resources.checks) checks.push(`${config}: ${check}`);
    } else {
      resourcesByConfig[config.toLowerCase()] = resources;
    }
  }
  if (checks.length > 0) {
    return { ok: false, checks, linkDir: link.linkDir, flagsFile: link.flagsFile };
  }
  rmSync(link.linkDir, { recursive: true, force: true });
  const variants = {};
  for (const [variant, config] of [['debug', 'Debug'], ['release', 'Release']]) {
    const headersDir = join(link.linkDir, config, 'Headers');
    const frameworksDir = join(link.linkDir, config, 'Frameworks');
    mkdirSync(headersDir, { recursive: true });
    mkdirSync(frameworksDir, { recursive: true });
    const srcDir = join(link.buildDir, `${config}-iphoneos`);
    const { frameworks, paths } = frameworksByConfig[variant];
    const frameworkSources = {};
    for (const name of frameworks) {
      const realBundle = join(srcDir, paths[name]);
      symlinkSync(
        relative(frameworksDir, realBundle),
        join(frameworksDir, `${name}.framework`),
        'dir',
      );
      symlinkSync(
        join('..', 'Frameworks', `${name}.framework`, 'Headers'),
        join(headersDir, name),
        'dir',
      );
      frameworkSources[name] = realBundle;
    }
    const { resources, paths: resourcePaths } = resourcesByConfig[variant];
    const resourceSources = {};
    for (const name of resources) {
      resourceSources[name] = join(srcDir, resourcePaths[name]);
    }
    variants[variant] = {
      config,
      headers: headersDir,
      frameworks_dir: frameworksDir,
      frameworks: [...frameworks],
      framework_sources: frameworkSources,
      resources: [...resources],
      resource_sources: resourceSources,
    };
  }
  const flags = {
    generated_by: 'scripts/build-player-identity.mjs --fetch-deps --platform ios',
    firebase_auth_ios: IDENTITY_PINS.firebaseAuthIos,
    google_sign_in_ios: IDENTITY_PINS.googleSignInIos,
    variants,
  };
  writeFileSync(link.flagsFile, `${JSON.stringify(flags, null, 2)}\n`);
  return { ok: true, checks: [], linkDir: link.linkDir, flagsFile: link.flagsFile, variants };
}

