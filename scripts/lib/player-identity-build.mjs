/**
 * Confirm the Podfile target names a static-library target that exists in
 * the template project, before `pod install` runs. Returns
 * `{ ok, target }` or `{ ok: false, error }`.
 */
export function checkPodsTargetAgreement(podfileText, pbxprojText) {
  const podfileTarget = /target '([^']+)'/.exec(String(podfileText));
  if (!podfileTarget) {
    return { ok: false, error: 'Podfile names no target' };
  }
  const nativeTargets = [];
  for (const line of String(pbxprojText).split('\n')) {
    if (!line.includes('isa = PBXNativeTarget')) continue;
    const name = /name = ([^;]+);/.exec(line);
    if (name) nativeTargets.push(name[1].trim());
  }
  if (!nativeTargets.includes(podfileTarget[1])) {
    return {
      ok: false,
      error: `Podfile target '${podfileTarget[1]}' is not a target of the Xcode project (has: ${nativeTargets.join(', ') || 'none'})`,
    };
  }
  return { ok: true, target: podfileTarget[1] };
}

